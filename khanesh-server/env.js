// بارگذارِ .env — باید *پیش از هر ماژولِ دیگری* ایمپورت شود.
//
// ⚠️ چرا فایلِ جدا: importها در ESM *پیش از* بدنهٔ همان فایل اجرا می‌شوند.
//    وقتی dotenv.config() داخلِ بدنهٔ server.js بود، auth.js (که AUTH_REQUIRED،
//    JWT_SECRET، SMSIR_API_KEY را هنگامِ *ایمپورت* می‌خواند) زودتر از .env
//    ارزیابی می‌شد. نتیجه: احراز هویت با وجودِ AUTH_REQUIRED=true در .env
//    خاموش می‌ماند و فرستندهٔ پیامک mock می‌شد — بی‌هیچ خطایی.
//    فقط یک ایمپورتِ جانبی، اولِ فهرستِ server.js، این ترتیب را تضمین می‌کند.
// ============================================================
import dotenv from 'dotenv';
import { fileURLToPath } from 'node:url';

dotenv.config();
// همان .env کنارِ همین فایل — تا اجرا از پوشهٔ دیگر هم درست کار کند.
dotenv.config({ path: fileURLToPath(new URL('.env', import.meta.url)) });
