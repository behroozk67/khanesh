/**
 * طبقه‌بندِ یکتا. خروجی یکی از این‌هاست یا null:
 *
 *   کلسیم بالا  + PTH بالا    + کلسیمِ ادرار پایین → 'fhh_pattern'
 *   کلسیم بالا  + PTH بالا    + کلیهٔ مختل        → 'hpt_renal_advanced'
 *   کلسیم بالا  + PTH بالا                        → 'hpt_primary'
 *   کلسیم بالا  + PTH پایین                       → 'hypercalcemia_pth_independent'
 *   کلسیم بالا  + PTH طبیعی                       → 'hypercalcemia_pth_indeterminate'
 *   کلسیم پایین + PTH بالا    + کلیهٔ مختل        → 'hpt_secondary_renal'
 *   کلسیم پایین + PTH بالا                        → 'hpt_secondary_nonrenal'
 *   کلسیم پایین + PTH پایین                       → 'hypoparathyroidism'
 *   کلسیم پایین + PTH طبیعی                       → 'hypocalcemia_pth_indeterminate'
 *
 * پیش‌شرطِ مطلق: هر دوی کلسیم و PTH روی برگه باشند. بدونِ PTH هیچ‌کدام از
 * این تفکیک‌ها ممکن نیست و محور کنار می‌کشد تا calcium_abnormalِ قدیمی
 * کارش را بکند — یعنی افزودنِ این فایل هیچ برگه‌ای را که PTH ندارد عوض نمی‌کند.
 *
 * ⚠️ «PTH طبیعی» عمداً به هیچ تشخیصی نگاشت نمی‌شود. متنِ منبع فقط سه حالتِ
 *    «بالا / پایین / طبیعی» را در جدول‌ها می‌دهد و برای کلسیمِ غیرطبیعی با
 *    PTHِ داخلِ محدوده حکمی ندارد. مفهومِ بالینیِ «طبیعیِ نامتناسب» واقعی
 *    است ولی در این منبع نوشته نشده — پس ساختنش یعنی اختراعِ محتوای بالینی،
 *    همان چیزی که این معماری برای جلوگیری از آن هست. به‌جایش یک یافتهٔ صریحاً
 *    «تفکیک‌نشده» ساخته می‌شود که می‌گوید چه چیزی جدا نشد و چرا.
 */
export function mineralAxis(e) {
  const ca  = g(e, "CA");
  const pth = g(e, "PTH");
  if (!ca?.abnormal || !pth || pth.value == null) return null;

  const caHigh = ca.dir === "high";

  if (caHigh) {
    if (hi(pth)) {
      if (lo(g(e, "U_CA")))  return "fhh_pattern";
      if (renalImpaired(e))  return "hpt_renal_advanced";
      return "hpt_primary";
    }
    if (lo(pth))  return "hypercalcemia_pth_independent";
    return "hypercalcemia_pth_indeterminate";
  }

  if (hi(pth)) {
    return renalImpaired(e) ? "hpt_secondary_renal" : "hpt_secondary_nonrenal";
  }
  if (lo(pth)) return "hypoparathyroidism";
  return "hypocalcemia_pth_indeterminate";
}

/** فوریت از خودِ شدتِ کلسیم می‌آید، نه از عددی که ما اختراع کنیم. */
function caUrgency(e) {
  return levelGrade(g(e, "CA")) >= 2 ? "this_week" : "routine";
}

/**
 * متنِ اقدام باید *از همان فوریت* بیاید، نه جدا نوشته شود.
 *
 * 🔴 باگِ واقعی، گرفته‌شده در دودتستِ خروجی پیش از کامیت: قاعده‌های محور
 *    فوریتشان را از شدتِ کلسیم می‌گرفتند ولی متنِ اقدامشان «این هفته … وقت
 *    بگیرید» هاردکد بود. روی Ca=۱۱.۴ (گرید ۱ → routine) بیمار یک یافتهٔ
 *    routine می‌گرفت که در متنش «این هفته» نوشته بود.
 *    تناقضِ فوریت با متن، از هر دو حالت بدتر است: کاربر نمی‌داند کدام را
 *    باور کند، و رابط کاربری روی فیلدِ urgency رنگ و ترتیب می‌سازد در حالی
 *    که چیزی که خوانده می‌شود جملهٔ اقدام است.
 * قفل‌شده با M70.
 */
function actionFor(urgency, { week, routine }) {
  return urgency === "this_week" ? week : routine;
}

