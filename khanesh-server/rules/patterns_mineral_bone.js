const g  = (e, k) => e.graded?.find((x) => x.test === k);
const hi = (x) => Boolean(x?.abnormal && x.dir === "high");
const lo = (x) => Boolean(x?.abnormal && x.dir === "low");
/** اندازه‌گیری شده و داخل محدوده — نه «اندازه‌گیری نشده». تفکیکِ N4. */
const mid = (x) => Boolean(x && x.value != null && !x.abnormal);

const rangeTxt = (x) => (x?.range ? ` (حد طبیعی ${x.range})` : "");

/**
 * آیا نشانهٔ افتِ کارِ کلیه روی همین برگه هست؟
 *
 * عیناً همان تعریفی که magnesium_abnormal استفاده می‌کند — عمداً یکسان،
 * چون اگر دو جای موتور دو تعریفِ متفاوت از «کلیهٔ مختل» داشته باشند،
 * بیمار می‌تواند یک یافته بگیرد که کلیه را درگیر می‌داند و یکی که نمی‌داند.
 */
function renalImpaired(e) {
  const creat = g(e, "CREAT");
  return hi(creat) || (e.indices?.egfr != null && e.indices.egfr < 60);
}

/**
 * کلسیمِ بحرانی — آستانه‌ای که calcium_abnormal با آن به اورژانس می‌رود.
 *
 * ⚠️ اینجا تعریف شد و به patterns_biochem.js صادر می‌شود تا *یک* عدد باشد.
 *    دلیلِ وجودی‌اش انحصار است: محورِ PTH حق ندارد قاعدهٔ کلسیمِ بحرانی را
 *    خاموش کند. اگر Ca=۱۵ باشد و PTH هم بالا، بیمار باید هم پیامِ اورژانس
 *    را بگیرد و هم علت را — نه اینکه یکی جای دیگری را بگیرد.
 */
export function caCritical(e) {
  const ca = g(e, "CA");
  return ca?.value != null && (ca.value >= 14 || ca.value <= 6.5);
}

/**
 * یادداشتِ کلسیمِ تصحیح‌شده — همان جمله‌ای که calcium_abnormal می‌گوید.
 * N5: اگر عددی که نقل می‌کنیم روی برگهٔ بیمار نیست، باید بگوییم.
 */
function corrNote(e) {
  return e.indices?.ca_correction_applied
    ? ` (این مقدار با آلبومین تصحیح شده؛ آنچه روی برگه چاپ شده ${e.indices.ca_measured} است.)`
    : "";
}

/**
 * شاخهٔ سه‌حالتهٔ فسفر — بالا / پایین / طبیعی / اندازه‌گیری‌نشده.
 *
 * ⚠️ این تابع اختیاری نیست. هر قاعدهٔ این فایل *باید* صدایش بزند، به دو دلیل:
 *   ۱. N4 — «فسفر پایین است» بخشی از تعریفِ هایپرپاراتیروئیدیِ اولیه است.
 *      اگر فسفر روی برگه نباشد و ما ساکت بمانیم، بیمار فرض می‌کند دیده شده.
 *   ۲. N18 — قاعده‌های این فایل، phosphate_abnormal را خاموش می‌کنند. آن
 *      انحصار فقط وقتی امن است که خودِ متن فسفر را نام ببرد، وگرنه یک فسفرِ
 *      غیرطبیعی کاملاً از گزارش ناپدید می‌شود. تورِ unexplained_abnormal هم
 *      دقیقاً همین نام‌بردن را می‌پاید.
 */
function phosClause(e, { expect } = {}) {
  const p = g(e, "PHOS");
  if ((!p || p.value == null) && ungradedFa(e, "PHOS", "فسفر")) {
    // P88: چاپ‌شده بی‌واحد ≠ «اندازه‌گیری نشده» (N4، گارد L8).
    return ` ${ungradedFa(e, "PHOS", "فسفر")}` +
      (expect ? ` — و در این الگو انتظار می‌رود ${expect}؛ آن را با پزشک مرور کنید.` : ".");
  }
  if (!p || p.value == null) {
    return " فسفر روی این برگه اندازه‌گیری نشده است" +
      (expect ? ` — و در این الگو انتظار می‌رود ${expect}؛ درخواستش را با پزشک مطرح کنید.` : ".");
  }
  const dirFa = hi(p) ? "بالاتر از حد طبیعی" : lo(p) ? "پایین‌تر از حد طبیعی" : "در محدودهٔ طبیعی";
  return ` فسفر شما ${p.value}${rangeTxt(p)} است، یعنی ${dirFa}.`;
}

/**
 * شاخهٔ سه‌حالتهٔ کلسیمِ ادرار. همان استدلالِ phosClause.
 *
 * این تنها متغیری است که هایپرپاراتیروئیدیِ اولیه را از FHH جدا می‌کند
 * (جدول ۱۶.۲: کلسیمِ ادرار «بالا» در برابر «پایین»، و بقیهٔ ستون‌ها یکسان).
 * پس «اندازه‌گیری نشده» اینجا یک اقدامِ درمانی است، نه یک سکوتِ بی‌ضرر —
 * FHH نیازی به جراحیِ پاراتیروئید ندارد و اولیه دارد.
 */
function uCaClause(e) {
  const u = g(e, "U_CA");
  if (!u || u.value == null) {
    return " کلسیم ادرار ۲۴ ساعته روی این برگه نیست؛ همین یک آزمایش است که " +
      "پرکاری واقعی پاراتیروئید را از یک حالت ارثیِ خوش‌خیم (که درمان جراحی لازم ندارد) جدا می‌کند.";
  }
  const dirFa = hi(u) ? "بالاتر از حد طبیعی" : lo(u) ? "پایین‌تر از حد طبیعی" : "در محدودهٔ طبیعی";
  return ` کلسیم ادرار ۲۴ ساعتهٔ شما ${u.value}${rangeTxt(u)} است، یعنی ${dirFa}.`;
}

/** آیا منیزیمِ پایین می‌تواند خودش عاملِ این تصویر باشد؟ (جعبهٔ ۱۶.۲ — علتِ برگشت‌پذیر) */
function mgLow(e) { return lo(g(e, "MG")); }

