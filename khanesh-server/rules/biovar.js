/** ضریبِ Z برای p<۰.۰۵ دوطرفه. */
const Z_95 = 1.96;

/**
 * RCV — کمترین تغییرِ درصدیِ بینِ دو نوبت که می‌شود «واقعی» دانستش.
 *
 *   RCV = √2 × Z × √(CVa² + CVi²)
 *
 * CVa (خطای تحلیلیِ دستگاه) را نداریم — به‌جای حدس، مشخصهٔ کیفیتِ
 * «مطلوب» را می‌گذاریم: CVa ≤ ۰.۵ × CVi (همان تعریفِ APS در EFLM).
 * پس RCV ≈ ۳.۱ × CVi. اگر آزمایشگاه CVaی خودش را داد، پاسش بده.
 *
 * @returns {number|null} درصد، گرد شده. null یعنی برای این تست داده نداریم.
 */
export function rcv(testKey, cva = null) {
  const bv = BV[testKey];
  if (!bv) return null;
  const a = cva ?? 0.5 * bv.cvi;
  return Math.round(Math.SQRT2 * Z_95 * Math.sqrt(a * a + bv.cvi * bv.cvi));
}

/**
 * شاخصِ فردیت = CVi / CVg.
 *   < ۰.۶ → بازهٔ مرجعِ جمعیتی برای این تست کم‌فایده است؛ تغییرِ نسبت به
 *           پایهٔ خودِ فرد مهم‌تر از داخل/خارجِ بازه بودن است.
 *   > ۱.۴ → بازهٔ مرجع خوب کار می‌کند.
 */
export function individualityIndex(testKey) {
  const bv = BV[testKey];
  if (!bv || !bv.cvg) return null;
  return +(bv.cvi / bv.cvg).toFixed(2);
}

/** آستانه‌ای که زیرش بازهٔ مرجع را باید با احتیاط خواند. */
export const LOW_INDIVIDUALITY = 0.6;

export function hasLowIndividuality(testKey) {
  const ii = individualityIndex(testKey);
  return ii != null && ii < LOW_INDIVIDUALITY;
}

/**
 * جملهٔ فارسیِ «تکرار» با عددِ معنادار.
 * مثال: «برای اینکه تغییرِ کراتینین واقعی حساب شود، باید بیش از حدود ۲۱٪
 *        با نوبتِ قبل فرق کند؛ کمتر از آن نوسانِ طبیعیِ بدن و دستگاه است.»
 *
 * @returns {string|null} null یعنی داده نداریم — چیزی نگو، عددِ حدسی نساز.
 */
export function repeatDeltaFa(testKey, faLabel) {
  const r = rcv(testKey);
  if (r == null) return null;
  const name = faLabel || testKey;
  return `اگر این تست تکرار شود، تغییرِ کمتر از حدود ${r}٪ در ${name} معمولاً ` +
         `نوسانِ طبیعیِ بدن و خطای دستگاه است، نه بهتر یا بدتر شدنِ واقعی ` +
         `(تغییرپذیریِ زیستی — ${GUIDELINES.EFLM_BV.org}).`;
}

/**
 * هشدارِ فردیتِ پایین — برای تستی که «طبیعی»اش هم می‌تواند برای این فرد بالا باشد.
 * فقط وقتی صدا کن که مقدار داخلِ بازه ولی نزدیکِ لبه است؛ وگرنه بیمار را
 * بی‌جهت نگران می‌کند.
 */
export function individualityCaveatFa(testKey, faLabel) {
  if (!hasLowIndividuality(testKey)) return null;
  const name = faLabel || testKey;
  return `${name} از آن دسته تست‌هایی است که نوسانِ خودِ هر فرد بسیار کمتر از ` +
         `تفاوتِ بینِ آدم‌هاست؛ بنابراین عددی که در «محدودهٔ طبیعیِ جمعیت» است ` +
         `می‌تواند نسبت به پایهٔ خودِ شما بالا باشد. مقایسه با نتیجهٔ قبلیِ خودتان ` +
         `معنادارتر از مقایسه با محدودهٔ چاپ‌شده است.`;
}

