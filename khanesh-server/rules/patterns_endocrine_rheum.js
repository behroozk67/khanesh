// ۲۰۲۶-۱۰-۱۶ (P108، N4/N21): در شاخهٔ thyroid_nonthyroidal_illness بی‌FT4، T4ِ تامِ چاپ‌شده نادیده گرفته می‌شد و متن فقط «FT4 اندازه‌گیری
//   نشده … نمی‌توان کنار گذاشت» می‌گفت. فوریت دست نخورد (N29). کلید عمداً بیرون از متنِ قاعده است تا RULE_READS آن را «خوانده‌شده» نشمارد (M156).
const TOTAL_T4 = "T4";
function totalT4CentralClause(e) {
  const g = e.graded.find((x) => x.test === TOTAL_T4);
  if (g && !g.abnormal) return `T4 تامِ شما ${g.value} (حد طبیعی ${g.range}) در محدوده است که کم‌کاریِ ناشی از غدهٔ هیپوفیز را کم‌احتمال‌تر می‌کند، ولی FT4 برای این تصمیم دقیق‌تر است.`;
  if (g?.dir === "low") return `T4 تامِ شما ${g.value} (حد طبیعی ${g.range}) هم پایین است، پس کم‌کاریِ ناشی از غدهٔ هیپوفیز را نمی‌توان کنار گذاشت.`;
  if (g) return `T4 تامِ شما ${g.value} بالاتر از حد طبیعی (${g.range}) است و با پایین‌بودنِ T3 هم‌خوان نیست؛ پزشک آن را کنارِ بقیهٔ نتایج می‌سنجد.`;
  return "بدونِ آن کم‌کاریِ ناشی از غدهٔ هیپوفیز را نمی‌توان کنار گذاشت.";
}

// ⚠️ C1: فقط در برابرِ بازهٔ چاپ‌شدهٔ همان ردیف یا واژهٔ آزمایشگاه (thyroidAbState در serology.js). هیچ عددِ ثابتی
//    (مثلاً «۳ برابرِ حدِ بالا در بارداری») این‌جا نیست؛ بارداری فقط یک جمله اضافه می‌کند و فوریت را عوض نمی‌کند.
// منبع: ATA 2016 (Ross و همکاران) — حساسیت/ویژگیِ TRAb برای گریوز، توصیه‌های ۹۲–۹۳ دربارهٔ TRAb در بارداری.
function thyroidAbNotable(e) {
  return ["ANTI_TG", "TRAB"].some((k) => ["above", "pos"].includes(thyroidAbState(e, k).state));
}

// CR5: عدد + واحدِ چاپ‌شده یک بار، با همان شکلِ برگه (نه raw که خودش واحد دارد).
function abValueFa(a) {
  return a.state === "above" || a.state === "within"
    ? `${a.shown ?? `${a.cmp ?? ""}${a.value}`}${a.unit ? " " + a.unit : ""}`
    : `«${a.raw}»`;
}

// B5 (بازبینیِ پزشکی): Anti-Tg در ایران بیشتر کنارِ تیروگلوبولین و برای پیگیریِ پس از درمانِ سرطانِ تیروئید درخواست می‌شود.
//   آن‌جا «هاشیموتو» و «اغلب فقط پیگیری» اطمینانِ کاذب است. نشانه: سرطانِ ثبت‌شده (فعال در conditions.js) یا ردیفِ تیروگلوبولین روی برگه.
function thyroidCancerContext(e) {
  if ((e.conditions ?? []).includes("cancer")) return true;
  // P144 (FR-004a): تیروگلوبولینِ نگاشت‌شده دیگر در unmapped نیست؛ بی این خط «Tg + Anti-Tg بالا» به متنِ «هاشیموتو… اغلب فقط پیگیری» می‌افتاد.
  if (e.ungraded?.THYROGLOBULIN?.reason === "assay_printed") return true;
  return [...(e.unmapped ?? []), ...Object.keys(e.qual ?? {})].some((n) => isThyroglobulinKey(n));
}

