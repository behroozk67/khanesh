export const NEONATAL_PERIOD_DAYS = 28;
export const isNeonate = (age) => age != null && age * 365 < NEONATAL_PERIOD_DAYS;
// دورهٔ گلبول‌های قرمزِ درشتِ نوزادی: عددِ تازه‌ای نیست — همان ردیفِ اولِ PED_REFS.MCV (۱۰۰–۱۳۰ fL). تا وقتی
// موتور خودش MCVِ نوزادی می‌دهد، بازهٔ بزرگسالِ شاخص‌هایی که با اندازهٔ سلول/جمعیتِ جنینی عوض می‌شوند غلط است.
export const inNeonatalRedCellPeriod = (age) => age != null && age <= PED_REFS.MCV[0].maxAge;
// 🔴 job c138671c: این کلیدها ردیفِ PED_REFS ندارند و قاعدهٔ عمومیِ RCPCH («بازهٔ بزرگسال») بازهٔ *زنِ بزرگسال* را
//    به نوزادِ ۱ روزه می‌داد: RBC با ۴.۱–۵.۱ (نوزادِ سالمِ ۵.۵ «بالا» می‌شد)، RDW-SD با ۳۵–۵۶ کنارِ MCVِ ۱۲۸. تا بازهٔ
//    نوزادیِ منبع‌دار (P57)، در این دوره سنجیده نمی‌شوند ⇒ noRef، و neonatal_reference_context دلیلش را می‌گوید.
export const NEONATAL_NO_ADULT_FALLBACK = new Set(['RBC', 'RDW_CV', 'RDW_SD']);

export function getRef(testKey, sex, age, { pregnant = false } = {}) {
  if (REPRO_HORMONE_KEYS.has(testKey) && ((age != null && age < 16) || !sex)) return null;
  if (NEONATAL_NO_ADULT_FALLBACK.has(testKey) && inNeonatalRedCellPeriod(age) && !getPedRef(testKey, age)) return null;
  // کورتیزولِ صبح/پس از دگزامتازون: بازهٔ بزرگسال برای زیر ۱۶ سال حدس است (P46) ⇒ سنجیده نمی‌شود، نه با بازهٔ بزرگسال.
  if ((testKey === 'CORTISOL_AM' || testKey === 'CORTISOL_DST') && age != null && age < 16) return null;
  // بیلی‌روبینِ غیرمستقیمِ نوزادِ < ۱۴ روز: بازهٔ منبع‌دار نداریم و بازهٔ بزرگسال (۰٫۱–۱) غلط است ⇒ سنجیده نمی‌شود (P63).
  if (testKey === 'BILI_I' && age != null && age * 365 < 14 && !getPedRef(testKey, age)) return null;
  if (testKey === 'HGB' && pregnant && sex === 'F') return hgbRef(sex, age, { pregnant });
  if (isPediatricRCPCH(age)) {
    const ped = getPedRef(testKey, age, sex);
    if (ped) return ped;
    // RCPCH: "If there is no age-specific paediatric range, use the adult range."
  }
  if (testKey === 'HGB') return hgbRef(sex, age);
  if (testKey === 'FERRITIN') return ferritinRef(sex, age);
  if (age >= GERIATRIC_FROM_AGE && GERIATRIC_REFS[testKey]) {
    const g = GERIATRIC_REFS[testKey];
    if (g.both) return g.both;
    return sex === 'M' ? g.M : g.F;
  }
  if (testKey === 'ESR')   return esrRef(sex, age);
  if (testKey === 'CREAT') return creatRef(age, sex);
  if (testKey === 'U_CA')  return uCaRef(sex, age);
  const r = ADULT_REFS[testKey];
  if (!r) return null;
  if (r.both) return r.both;
  // پرولاکتین (P46 بند ۱، FR-005): جنسیتِ نامعلوم حدِ پایین‌تر (مرد) را می‌گیرد، نه بازهٔ زن که کم‌خوانی می‌کند.
  if (testKey === 'PRL' && !sex) return r.M;
  return sex === 'M' ? r.M : r.F;
}

// specs/008 — «تأییدِ کاربر ۱۴۰۵/۰۷/۰۱؛ مرجعِ چسبانده‌شده، منبعِ اصلی نامعلوم». هیچ کتابی ادعا نمی‌شود.
export const SPECS008_SOURCE = 'User-approved 1405/07/01 (specs/008)';
const SPECS008_KEYS = new Set(['HGB', 'IRON', 'FERRITIN', 'HBA2', 'HBF']);
export const SPECS009_SOURCE = 'Pasted reference, pending review (specs/009, P56)';

// منبع محدوده — برای شفافیت
export function getRefSource(testKey, age) {
  // ⚠️ برچسبِ ثابتِ «RCPCH 2016» جای خود را به منبعِ همان ردیف داد — بعضی
  //    ردیف‌های PED_REFS عددشان از هنری می‌آید و RCPCH نگفته است. قفل: M79c.
  if (isPediatricRCPCH(age) && getPedRef(testKey, age)) return getPedRefSource(testKey, age);
  if (age >= 75 && GERIATRIC_REFS[testKey]) return 'Geriatric Override';
  // فصل ۲۶ (P47): حدهای منی از WHO 2021 است نه جدولِ A5ِ هنری — برچسبِ منبع باید راست بگوید.
  if (/^(SEMEN_|SPERM_)/.test(testKey)) return testKey === 'SEMEN_PH' ? 'Henry ch.26' : 'WHO 2021';
  if (testKey === 'TESTO') return 'Henry ch.26';
  // P46 بند ۱: عددِ ۲۰/۲۵ حدِ بالای رایجِ آزمایشگاه‌هاست؛ از جدولِ هنری نقل نشده.
  if (testKey === 'PRL') return 'Typical lab upper limit (P46)';
  if (testKey === 'CORTISOL_AM') return 'Typical lab range (P46)';
  if (testKey === 'CORTISOL_DST') return 'Endocrine Society 2008 (P46)';
  // specs/008: بازه‌هایی که کاربر به‌عنوانِ بازبین تأیید کرد — عدد از مرجعِ چسبانده‌شده، منبعِ اصلی نامعلوم.
  //   HGBِ ۱۲ تا ۱۵ ساله بازهٔ قدیمیِ بزرگسال را نگه داشته (R1)، پس برچسبِ قدیمی را می‌گیرد.
  if (SPECS008_KEYS.has(testKey) && !(testKey === 'HGB' && age != null && age < 16)) return SPECS008_SOURCE;
  // specs/009: حدِ پایینِ ۲۰۰ از هنری نیست — تا تأییدِ P56 برچسبِ «در انتظارِ بازبینی» می‌گیرد، نه ادعای منبع.
  if (testKey === 'MONO_ABS') return SPECS009_SOURCE;
  if (testKey === 'U_CA' && age != null && age >= U_CA_MAYO_FROM_AGE) return U_CA_MAYO_SOURCE;
  return 'Henry A5';
}

