// همان شکلِ patterns_cardiac.js: فوریت یک‌بار حساب می‌شود و جملهٔ اقدام از همان مشتق می‌شود (N20).
function actionFor(urgency, { week, routine }) {
  return urgency === "this_week" ? week : routine;
}
// «آیا آن قاعده فعال است» با matchِ زنده، نه کپیِ آستانه‌اش (M91e). ruleFiresById در hematology فقط RULES_HEMATOLOGY را می‌گردد.
function firesById(e, id) {
  const r = RULES_MALIGNANCY.find((x) => x.id === id);
  return r ? !!r.match(e) : false;
}
function firesHemById(e, id) {
  const r = RULES_HEMATOLOGY.find((x) => x.id === id);
  return r ? !!r.match(e) : false;
}
