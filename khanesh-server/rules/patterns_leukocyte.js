// هر قاعده جهت را از dirِ سنجیده‌شده می‌گیرد، نه از مقایسه با یک مرزِ شدت (N12)؛ و چون خواندنِ یک کلید آن را برای
// تورِ «توضیح داده نشدند» پوشش‌داده می‌کند، هر شاخه‌ای که کلید در آن فعال است جملهٔ خودش را دارد (M156).
import { MONOCYTOSIS_ABS_UL, HYPEREOSINOPHILIA_ABS_UL, smearAxis, smearItemFa, smearLeukemicSentence } from "./patterns_utils.js";
import { RULES_MALIGNANCY } from "./patterns_malignancy.js";

// همان شکلِ patterns_cardiac.js: فوریت یک‌بار حساب می‌شود و جملهٔ اقدام از همان مشتق می‌شود (N20).
function actionFor(urgency, { week, routine }) {
  return urgency === "this_week" ? week : routine;
}
// «آیا آن قاعده فعال است» با matchِ زنده، نه کپیِ آستانه‌اش (M91e). ruleFiresById در hematology فقط RULES_HEMATOLOGY را می‌گردد.
function firesById(e, id) {
  const r = RULES_MALIGNANCY.find((x) => x.id === id);
  return r ? !!r.match(e) : false;
}
const gradedOf = (e, key) => e.graded.find((g) => g.test === key);
const ROUTINE_ACTION = "نتیجه را در نوبتِ عادی با پزشک در میان بگذارید.";

export const RULES_LEUKOCYTE = [
  // ─────────── مونوسیتِ بالا ───────────
  {
    id: "monocytosis",
    match: (e) => {
      const m = gradedOf(e, "MONO_ABS");
      return !!(m?.abnormal && m.dir === "high");
    },
    build: (e) => {
      const m = gradedOf(e, "MONO_ABS");
      const w = gradedOf(e, "WBC");
      // درصد روی خروجیِ موتور نیست؛ از همان دو عددِ سنجیده‌شده حساب می‌شود و فقط وقتی WBC روی برگه است.
      const pct = w?.value > 0 ? Math.round(m.value / (w.value * 10)) : null;
      const pctFa = pct != null ? `، یعنی حدودِ ${pct}٪ از گلبول‌های سفید` : "";
      const strong = m.value >= MONOCYTOSIS_ABS_UL;
      return {
        pattern: "monocytosis",
        urgency: "routine",
        headline: strong ? "تعداد مونوسیت‌های خون شما بالاست" : "تعداد مونوسیت‌های خون شما کمی بالاتر از حد طبیعی است",
        must_say: strong
          ? `مونوسیت شما ${m.value} است (حد طبیعی ${m.range})${pctFa}. به این افزایش «مونوسیتوز» می‌گویند. ` +
            "شایع‌ترین علت‌ها عفونت‌های طول‌کشیده، بیماری‌های التهابیِ مزمن و دورهٔ بهبود پس از یک عفونت است. " +
            "اگر در تکرار هم بالا بماند، به‌ویژه در سنینِ بالاتر، پزشک با بررسیِ لامِ خون علت را دنبال می‌کند."
          : `مونوسیت شما ${m.value} است که کمی بالاتر از حد طبیعی (${m.range}) است${pctFa}. ` +
            "این مقدار افزایش به‌تنهایی معمولاً معنای خاصی ندارد و اغلب پس از یک عفونت یا التهابِ گذرا دیده می‌شود.",
        action: strong ? "نتیجه را در نوبتِ عادی با پزشک در میان بگذارید؛ تکرارِ CBC چند هفته بعد روندِ آن را نشان می‌دهد." : ROUTINE_ACTION,
        suggest: strong ? ["تکرار CBC", "گسترش خون محیطی"] : ["تکرار CBC"],
        warnings: [],
        key_number: m.value,
      };
    },
  },

  // ─────────── مونوسیتِ پایین ───────────
  // سه‌راهه بر اساسِ WBC (N4): پایین / پایین‌نبودن / روی برگه نبودن. روی شمارشِ دستیِ ۳٪ از WBCِ ۵ فعال می‌شود — ورودیِ
  // معمولیِ آدمِ سالم — پس روتین است و هشدار نمی‌دهد (پژوهش R2).
  {
    id: "monocytopenia",
    match: (e) => {
      const m = gradedOf(e, "MONO_ABS");
      return !!(m?.abnormal && m.dir === "low");
    },
    build: (e) => {
      const m = gradedOf(e, "MONO_ABS");
      const w = gradedOf(e, "WBC");
      const wbcLow = !!(w?.abnormal && w.dir === "low");
      const alone = "مونوسیتِ کمی پایین به‌تنهایی معمولاً معنای خاصی ندارد؛ شمارشِ دستی عددِ مونوسیت را با خطای زیادی می‌دهد و داروهای کورتونی هم آن را موقتاً پایین می‌آورند.";
      const context = wbcLow
        ? ` گلبول سفیدِ شما هم پایین است (${w.value})؛ پس کم بودنِ مونوسیت بخشی از همان افتِ کلیِ گلبول‌های سفید است و جدا از آن تفسیر نمی‌شود.`
        : w
        ? ` گلبول سفیدِ شما پایین نیست (${w.value}). ${alone}`
        : ` تعدادِ کلِ گلبول‌های سفید روی این برگه نیست، پس نمی‌شود گفت این کاهش بخشی از افتِ کلیِ گلبول‌هاست یا نه. ${alone}`;
      return {
        pattern: "monocytopenia",
        urgency: "routine",
        headline: "تعداد مونوسیت‌های خون شما پایین است",
        must_say: `مونوسیت شما ${m.value} است (حد طبیعی ${m.range}).${context}`,
        action: ROUTINE_ACTION,
        suggest: wbcLow ? [] : ["تکرار CBC"],
        warnings: [],
      };
    },
  },

  // ─────────── ائوزینوفیلِ بالا ───────────
  // بالای حدِ مرجع = ائوزینوفیلی (بی‌عددِ تازه)؛ از ۱۵۰۰ و سنجیده‌شده‌بالا = هایپرائوزینوفیلی. نوزادِ ۱۸۰۰ درونِ بازهٔ خودش است.
  {
    id: "eosinophilia",
    match: (e) => {
      const x = gradedOf(e, "EOS_ABS");
      return !!(x?.abnormal && x.dir === "high");
    },
    build: (e) => {
      const x = gradedOf(e, "EOS_ABS");
      const hyper = x.value >= HYPEREOSINOPHILIA_ABS_UL;
      const urgency = hyper ? "this_week" : "routine";
      return {
        pattern: "eosinophilia",
        urgency,
        headline: hyper ? "تعداد ائوزینوفیل‌های خون شما خیلی بالاست" : "تعداد ائوزینوفیل‌های خون شما بالاتر از حد طبیعی است",
        must_say: hyper
          ? `ائوزینوفیل شما ${x.value} است (حد طبیعی ${x.range})، یعنی بالای ${HYPEREOSINOPHILIA_ABS_UL} — به این سطح «هایپرائوزینوفیلی» می‌گویند. ` +
            "علت‌ها همان حساسیت‌ها، برخی داروها و انگل‌ها هستند، ولی این مقدار اگر پایدار بماند می‌تواند به بافت‌هایی مثل قلب، ریه و پوست آسیب بزند؛ " +
            "پس علتش باید پیدا شود و عدد در چند هفته تکرار شود."
          : `ائوزینوفیل شما ${x.value} است (حد طبیعی ${x.range}). ائوزینوفیل‌ها گلبول‌های سفیدی‌اند که در حساسیت و در پاسخ به انگل‌ها زیاد می‌شوند؛ ` +
            "شایع‌ترین علت‌ها حساسیت‌های فصلی، آسم، اگزما، برخی داروها و انگل‌های روده‌ای است.",
        action: actionFor(urgency, {
          week: "این هفته با پزشک وقت بگیرید و فهرستِ داروها و مکمل‌هایی را که مصرف می‌کنید همراه ببرید.",
          routine: ROUTINE_ACTION,
        }),
        suggest: hyper ? ["تکرار CBC", "آزمایش مدفوع برای انگل", "گسترش خون محیطی"] : ["آزمایش مدفوع برای انگل"],
        warnings: hyper ? ["اگر تنگیِ نفس، درد قفسهٔ سینه، تب یا بثوراتِ پوستیِ تازه دارید، زودتر مراجعه کنید."] : [],
        key_number: x.value,
      };
    },
  },

  // ─────────── بازوفیلِ بالا ───────────
  // مالکِ بازوفیل در WBCِ بالای ۵۰ هزار cml_suspicion است؛ آنجا کنار می‌کشد تا دو یافته دربارهٔ یک عدد نباشد (N20).
  {
    id: "basophilia",
    match: (e) => {
      const b = gradedOf(e, "BASO_ABS");
      if (!(b?.abnormal && b.dir === "high")) return false;
      return !firesById(e, "cml_suspicion");
    },
    build: (e) => {
      const b = gradedOf(e, "BASO_ABS");
      return {
        pattern: "basophilia",
        urgency: "routine",
        headline: "تعداد بازوفیل‌های خون شما بالاتر از حد طبیعی است",
        must_say:
          `بازوفیل شما ${b.value} است (حد طبیعی ${b.range}). بازوفیل‌ها کمیاب‌ترین گلبول‌های سفیدند و افزایشِ کمِ آن‌ها بیشتر در حساسیت‌ها، ` +
          "التهاب‌های مزمن و کم‌کاریِ تیروئید دیده می‌شود. در موارد کمتر، افزایشِ پایدارِ بازوفیل‌ها با بیماری‌های مغزِ استخوان همراه است؛ " +
          "به همین دلیل پزشک آن را کنارِ بقیهٔ شمارشِ خون می‌سنجد.",
        action: "نتیجه را در نوبتِ عادی با پزشک در میان بگذارید؛ تکرارِ CBC روندِ آن را نشان می‌دهد.",
        suggest: ["تکرار CBC"],
        warnings: [],
      };
    },
  },

  // ─────────── لامِ خونِ محیطی: بلاست، میله‌های اوئر، ناهنجاری‌های شکلِ گلبول سفید ───────────
  // یک طبقه‌بند (smearAxis)، یک یافته برای همهٔ آیتم‌ها — بلاست و اوئر در یک جمله ادغام می‌شوند (FR-006) و آیتم‌ها با هم
  // رقابتِ زمان‌بندی ندارند. وقتی acute_leukemia_suspicion فعال است، بلاست/اوئر مالِ آن است و اینجا کنار گذاشته می‌شود.
  // آیتم‌های لام در engineOut.abnormal نیستند، پس تورِ «توضیح داده نشدند» نمی‌بیندشان: پنهان‌شدن زیرِ blocker یعنی حذفِ
  // خاموش — always_show + brief. must_say زمان‌بندی ندارد؛ دستور فقط در action است (N20).
  {
    id: "peripheral_smear_findings",
    match: (e) => !!smearAxis(e, firesById(e, "acute_leukemia_suspicion") ? { exclude: "leukemic" } : {}),
    build: (e) => {
      const ax = smearAxis(e, firesById(e, "acute_leukemia_suspicion") ? { exclude: "leukemic" } : {});
      const has = (k) => ax.items.find((i) => i.kind === k);
      const leuk = ax.items.filter((i) => ax.leukemic.includes(i));
      const s = [];
      if (leuk.length) {
        s.push(`${smearLeukemicSentence(leuk)} این یافته می‌تواند نشانهٔ یک بیماریِ حادِ مغزِ استخوان (مثل لوسمیِ حاد) باشد و فقط با بررسیِ تخصصیِ مغزِ استخوان تأیید یا رد می‌شود.`);
      }
      const bl = has("blasts");
      if (bl && !leuk.includes(bl)) {
        s.push(`در بررسیِ لامِ خونِ شما بلاست — سلولِ نابالغی که معمولاً در خونِ سالم دیده نمی‌شود — ${bl.pct != null ? `${bl.pct}٪ ` : ""}گزارش شده است. ` +
          "مقدارِ کمِ آن گاهی در عفونت‌های شدید یا دورهٔ بهبودِ مغزِ استخوان هم دیده می‌شود، ولی علتش باید با بررسیِ متخصصِ خون روشن شود.");
      }
      if (has("pseudo_pelger")) {
        s.push("سلول‌های شبه‌پلگر (نوتروفیل‌هایی با هستهٔ کم‌قطعه) در لامِ شما گزارش شده‌اند. این تغییر اکتسابی است و می‌تواند نشانهٔ اختلال در ساختِ سلول‌های خون در مغزِ استخوان باشد؛ باید متخصصِ خون آن را بررسی کند.");
      }
      const reactive = ["toxic_granulation", "dohle"].map(has).filter(Boolean);
      if (reactive.length) {
        s.push(`در لامِ خونِ شما ${reactive.map(smearItemFa).join(" و ")} گزارش شده است — تغییراتی در گلبول‌های سفید که معمولاً پاسخِ بدن به عفونت یا التهاب است و با بهبودِ آن از بین می‌رود.`);
      }
      if (has("pelger")) {
        s.push("ناهنجاریِ پلگر-هوئت در لامِ شما گزارش شده است: شکلِ هستهٔ نوتروفیل‌ها متفاوت است. نوعِ ارثیِ آن بی‌خطر است و کارِ نوتروفیل‌ها طبیعی می‌ماند، ولی همین شکلِ هسته می‌تواند اکتسابی هم باشد و نشانهٔ اختلال در ساختِ سلول‌های خون در مغزِ استخوان — به‌ویژه اگر بخشِ دیگری از شمارشِ خونِ شما هم غیرطبیعی باشد. افتراقِ این دو نوع با پزشک است.");
      }
      if (has("may_hegglin")) {
        s.push("ناهنجاریِ می-هگلین در لامِ شما گزارش شده است — یک ویژگیِ ارثی که با پلاکت‌های درشت و گاهی کم بودنِ تعدادِ پلاکت همراه است؛ گلبول‌های سفید کارِ طبیعی دارند. پزشک آن را در کنارِ شمارشِ پلاکت می‌سنجد.");
      }
      if (has("alder_reilly")) {
        s.push("ناهنجاریِ آلدر-رایلی در لامِ شما گزارش شده است: دانه‌های درشت در گلبول‌های سفید که ارثی است و به‌تنهایی به کارِ آن‌ها آسیبی نمی‌زند؛ گاهی همراهِ بیماری‌های ارثیِ متابولیک دیده می‌شود و پزشک آن را در این زمینه می‌سنجد.");
      }
      if (has("chediak_higashi")) {
        s.push("گرانول‌های چدیاک-هیگاشی در لامِ شما گزارش شده است — دانه‌های غول‌آسا در گلبول‌های سفید که در یک بیماریِ ارثیِ نادر دیده می‌شود و با عفونت‌های مکرر همراه است. پزشک باید آن را در کنارِ سابقهٔ عفونت‌های شما بررسی کند.");
      }
      const urgency = ax.urgency;
      return {
        pattern: "peripheral_smear_findings",
        urgency,
        headline: urgency === "emergency" ? "سلول‌های نابالغ در لامِ خونِ شما گزارش شده است"
          : urgency === "this_week" ? "یافته‌ای در لامِ خونِ شما که باید بررسی شود"
          : "تغییراتی در شکلِ گلبول‌های سفید در لامِ خونِ شما",
        must_say: s.join(" "),
        brief: `در لامِ خونِ شما این موارد هم گزارش شده است: ${ax.items.map(smearItemFa).join("، ")}.`,
        always_show: true,
        action: urgency === "emergency"
          ? "همین امروز به اورژانسِ یک بیمارستان (ترجیحاً دارای بخشِ خون) مراجعه کنید و این برگه را همراه ببرید."
          : urgency === "this_week" ? "این هفته با پزشک (ترجیحاً متخصصِ خون) وقت بگیرید و این برگه را همراه ببرید."
          : ROUTINE_ACTION,
        suggest: urgency === "routine" ? [] : ["تکرار CBC", "گسترش خون محیطی"],
        warnings: [],
        ...(bl?.pct != null ? { key_number: bl.pct } : {}),
      };
    },
  },
];
