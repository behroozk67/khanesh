// پیش از این فایل مونوسیت، ائوزینوفیل و بازوفیلِ غیرطبیعی هیچ قاعده‌ای نداشتند و فقط «توضیح آماده‌ای نداریم»
// می‌گرفتند (اندازه‌گیری‌شده روی 0d8c782). همهٔ عددهای تازه در MEDICAL_RULES.md P56 «در انتظارِ بازبینی»‌اند.
