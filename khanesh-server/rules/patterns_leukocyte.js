  // پان‌سیتوپنی. بینِ ۵۰ و حدِ پایین قاعده هنوز فعال می‌شود ولی فقط یک یادداشتِ بی‌دستور و بی‌پیشنهاد است؛ بی آن، عدد به تورِ
  // «توضیح داده نشدند» می‌رسید که می‌گوید «موتور نتیجه‌گیری نکرده، نه اینکه بی‌اهمیت‌اند» — یعنی همان هشدار با لحنِ بدتر (N18).
