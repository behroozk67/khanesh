/** گریدشدهٔ یک کلید، یا undefined. */
const g = (e, key) => e.graded?.find((x) => x.test === key);

/**
 * آیا روی این برگه تروپونینِ *کیفیِ* مثبتی هست؟
 *
 * ⚠️ این دقیقاً همان عبارتی است که troponin_positive در patterns_biochem.js
 *    استفاده می‌کند، و اینجا برای *نفی* به کار می‌رود. قاعدهٔ زیر باید با آن
 *    قاعده ناسازگارِ ساختاری باشد نه اتفاقی: آن یکی با «غیرطبیعیِ بالا یا
 *    کیفیِ مثبت» فعال می‌شود و این یکی با «غیرطبیعی نیست و کیفیِ مثبت هم
 *    نیست». دو شرط مکملِ هم‌اند، پس هرگز با هم فعال نمی‌شوند — و چون آن یکی
 *    `blocks_others` دارد، اگر هم‌زمان می‌شدند این یکی بی‌صدا سرکوب می‌شد و
 *    کسی نمی‌فهمید. قفل: M85c.
 */
function troponinQualPositive(e) {
  return Object.entries(e.qual || {}).some(
    ([k, v]) => /troponin|ctn[it]|hs.?ctn|cardiac.?troponin/i.test(k) && qualVerdict(v).state === "pos"
  );
}

/**
 * وضعیتِ یک آزمایشِ کمکی روی همین برگه: "high" | "low" | "normal" | "absent".
 *
 * ⚠️ چهار حالت، نه سه و نه دو — کلاسِ N4 و N21. متنی که می‌گوید «B12 شما
 *    طبیعی است» وقتی B12 اصلاً روی برگه نیست، ادعای کاذب است؛ و متنی که
 *    «طبیعی» و «غایب» را یکی می‌گیرد همان کار را با یک `else` انجام می‌دهد.
 */
function statusOf(e, key) {
  const x = g(e, key);
  if (!x) return "absent";
  if (!x.abnormal) return "normal";
  return x.dir === "high" ? "high" : "low";
}

