/** فوریت و جملهٔ اقدام از یک تصمیم (N20)؛ کپیِ محلی، مثلِ patterns_cardiac/hematology/mineral_bone. */
function actionFor(urgency, { week, routine }) {
  return urgency === "this_week" ? week : routine;
}

const axisIs = (label) => (e) => castAxis(e).label === label;

/**
 * کراتینینِ همین برگه، پنج‌شاخه (اصلِ دوم، N4، N21).
 * ⚠️ «روی برگه نیست» فقط وقتی گفته می‌شود که واقعاً نیست: کراتینینِ بی‌واحد در e.ungraded است، نه
 *    e.graded (specs/003)، و دوشاخه‌ای‌کردنِ این به بیمار می‌گفت آزمایشی را که روی برگه‌اش چاپ شده ندارد.
 * ⚠️ عدد نقل نمی‌شود: مقدارِ graded ممکن است از µmol/L تبدیل شده و روی کاغذِ بیمار نباشد (N5).
 */
export function creatClause(e) {
  const cr = e.graded?.find((g) => g.test === "CREAT");
  if (cr?.abnormal && cr.dir === "high") {
    return { text: "کراتینینِ همین برگه هم بالاتر از حدِ طبیعی است، که درگیریِ کلیه را محتمل‌تر می‌کند.", absent: false };
  }
  if (cr?.abnormal && cr.dir === "low") {
    return { text: "کراتینینِ همین برگه کمی پایین است، که دربارهٔ این یافته چیزی نمی‌گوید.", absent: false };
  }
  if (cr) {
    return { text: "کراتینینِ همین برگه در محدودهٔ طبیعی است؛ یعنی کارِ تصفیهٔ کلیه فعلاً افت نکرده، ولی این یافته همچنان بررسی می‌خواهد.", absent: false };
  }
  if (e.ungraded?.CREAT) {
    return { text: "کراتینین روی برگه هست ولی واحدش مشخص نیست، پس اینجا سنجیده نشد؛ پزشک آن را کنارِ این یافته می‌خواند.", absent: false };
  }
  return { text: "کراتینین روی این برگه نیست؛ برای سنجیدنِ کارِ کلیه، این آزمایش قدمِ بعدیِ لازم است.", absent: true };
}

