  //    ۱۵۰–۳۹۹ را می‌گیرد و هیچ قاعده‌ای زیرِ ۱۵۰ نداشت. یعنی موتور موردِ
  //    *مرزی* را توضیح می‌داد و دربارهٔ کمبودِ *آشکار* ساکت بود: B12=۸۰ روی
