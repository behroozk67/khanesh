//  • اورژانس فقط وقتی هر خوانشِ ممکن اورژانس است، یا عدد بیرون از محدودهٔ خودِ آزمایشگاه به حدِ
//    اورژانس است (بازبینیِ پزشکی B3، B5) — باز هم بی‌جهت.
//  • فقط عددِ برگه نقل می‌شود، نه عددِ تبدیل‌شده (N5).
