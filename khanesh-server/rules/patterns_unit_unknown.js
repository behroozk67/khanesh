//  • فوریت را این فایل حساب نمی‌کند — adapter برای هر ردیف `urgency` را از خودِ موتور گرفته است
//    (کمینه روی خوانش‌های ممکن، یا عدد نسبت به محدودهٔ چاپ‌شده). اینجا فقط بیشینهٔ ردیف‌ها، و همان
