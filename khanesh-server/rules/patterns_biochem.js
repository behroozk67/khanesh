// P88 (۲۰۲۶-۱۰-۰۵، LIS بیمارستان؛ N21/N8): ckmb_high تروپونینِ روی همان برگه را نمی‌گفت و دوباره درخواستش می‌کرد. بیرون از قاعده،
//   تا TROPONIN_I در RULE_READSِ ckmb_high نیاید و جهتِ دیگرش بی‌صدا «پوشش‌داده» نشود (M156). تروپونینِ بالا مالکِ خودش را دارد.
function ckmbTroponinClause(e) {
  const tn = e.graded.find((g) => g.test === "TROPONIN_I");
  if (tn && !tn.abnormal) return ` تروپونین هم روی برگهٔ شما هست و ${tn.value} (حد طبیعی ${tn.range})، یعنی در محدوده است.`;
  const u = ungradedFa(e, "TROPONIN_I", "تروپونین");
  return u ? ` ${u}.` : "";
}

