const KETONE_RE = /ketone|کتون|hydroxybutyrate|بتاهیدروکسی/i;

/** بالاترین قندِ ثبت‌شده روی برگه (ناشتا/تصادفی/دوساعته)، به‌عنوان رکوردِ graded. */
function topGlucose(e) {
  const cand = ["GLU_F", "GLU_RANDOM", "GLU_2H"]
    .map((k) => e.graded.find((g) => g.test === k))
    .filter((g) => g?.value != null);
  if (!cand.length) return null;
  return cand.reduce((a, b) => (b.value > a.value ? b : a));
}

/**
 * وضعیتِ کتون: "positive" | "negative" | "absent".
 * ⚠️ سه‌حالته، نه دوحالته: «اندازه‌گیری‌نشده» با «منفی» یکی نیست. همان چیزی
 *    که N4 دربارهٔ کراتینین می‌گوید — تستِ نبوده، تستِ طبیعی نیست.
 */
function ketoneState(e) {
  const tested = !!e.qual && Object.keys(e.qual).some((k) => /ketone|کتون/i.test(k));
  if (!tested) return "absent";
  return urinePositive(e, KETONE_RE) ? "positive" : "negative";
}

/** وضعیتِ بی‌کربنات: "low" | "normal" | "absent" — به همان دلیلِ بالا سه‌حالته. */
function hco3State(e) {
  const g = e.graded.find((x) => x.test === "HCO3");
  if (!g || g.value == null) return "absent";
  return g.abnormal && g.dir === "low" ? "low" : "normal";
}

