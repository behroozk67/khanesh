/** فوریت و جملهٔ اقدام از یک تصمیم (N20)؛ کپیِ محلی، مثلِ patterns_urine_casts. */
function actionFor(urgency, { week, routine }) {
  return urgency === "this_week" ? week : routine;
}

const REPEAT_UA_MORNING = "کامل ادرار — تکرار با نمونهٔ اولِ صبح";
const REPEAT_UA_MIDSTREAM = "کامل ادرار — تکرار با نمونهٔ وسطِ ادرار، پس از شستنِ ناحیهٔ تناسلی";
