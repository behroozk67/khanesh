const faList = (types) => {
  const o = types.map((t) => CRYSTAL_FA[t]);
  return o.length === 1 ? o[0] : `${o.slice(0, -1).join("، ")} و ${o[o.length - 1]}`;
};

// ── مالک‌های بیلی‌روبینِ خون (FR-021). جست‌وجو هنگامِ اجرا، نه هنگامِ بارگذاری، تا ترتیبِ importها مهم نباشد.
const ruleById = (list, id) => list.find((r) => r.id === id);
// 🔴 بازبینیِ پزشکی B1 / کد #۱: «match فعال شد؟» کافی نبود — هر دو مالک شاخه‌ای دارند که کبد را رد می‌کند
//    (ژیلبر؛ «عضله نه خون»). جملهٔ نوار به آن‌ها چسبیده بود و یافتهٔ «این هفته» گم می‌شد. حالا مالک فقط شاخه‌ای است
//    که واقعاً ساخته می‌شود *و* دربارهٔ کبد/صفرا یا تجزیهٔ گلبول حرف می‌زند. شاخهٔ ژیلبر با بیلی‌روبینِ ادرارِ مثبت
//    دیگر ساخته نمی‌شود (patterns_biochem)؛ شاخهٔ عضله مالک نیست و یافتهٔ ادرار مستقل می‌ماند.
const SERUM_BILI_OWNER_PATTERNS = new Set(["bilirubin_direct_dominant", "bilirubin_indirect_dominant", "hemolysis_likely"]);
function serumBiliOwnerFires(e) {
  if (biliEmergencyOwns(e)) return true;
  for (const r of [ruleById(RULES_BIOCHEM, "bilirubin_pattern"), ruleById(RULES_HEMATOLOGY, "hemolysis_pattern")]) {
    if (r?.match(e) && SERUM_BILI_OWNER_PATTERNS.has(r.build(e)?.pattern)) return true;
  }
  return false;
}

/** بیلی‌روبینِ خونِ همین برگه، چهارشاخه (اصلِ دوم، N4) — عدد نقل نمی‌شود (N5). */
function serumBiliClause(e) {
  const bt = e.graded?.find((g) => g.test === "BILI_T");
  if (bt?.abnormal && bt.dir === "high") return " بیلی‌روبینِ خونِ همین برگه هم بالاست، که با همین تصویر جور است.";
  if (bt) return " بیلی‌روبینِ تامِ خونِ همین برگه در محدودهٔ طبیعی است؛ نوار گاهی زودتر از خون تغییر می‌کند و گاهی مثبتِ کاذب می‌دهد، پس پزشک آن را کنارِ آزمایش‌های کبد می‌خواند.";
  if (e.ungraded?.BILI_T) return " بیلی‌روبینِ خون روی برگه هست ولی واحدش مشخص نیست، پس اینجا سنجیده نشد.";
  return " بیلی‌روبینِ خون روی این برگه نیست؛ آزمایش‌های خونِ کبد این یافته را تأیید و دقیق‌تر می‌کنند.";
}

/** هموگلوبینِ همین برگه، سه‌شاخه — برای «تجزیهٔ گلبول‌ها». */
function hbClause(e) {
  const hb = e.graded?.find((g) => g.test === "HGB");
  if (hb?.abnormal && hb.dir === "low") return " هموگلوبینِ همین برگه هم پایین است، که تجزیهٔ بیشترِ گلبول‌ها را محتمل‌تر می‌کند.";
  if (hb) return " هموگلوبینِ همین برگه پایین نیست.";
  return " شمارشِ خون روی این برگه نیست؛ همراهِ بیلی‌روبینِ خون، این دو جهت را روشن می‌کنند.";
}

