const WBC_RE = /wbc|pus\s*cells?|پوس\s*سل|leukocyt/i;   // ۲۰۲۶-۱۰-۰۳: «Pus cell» با فاصله جور نمی‌شد و پیوری بی‌صدا می‌افتاد
