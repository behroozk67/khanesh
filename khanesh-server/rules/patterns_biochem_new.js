// ═══════════ کمک‌کننده‌های شکِ هایپرکلسترولمی فامیلی (FH) ═══════════
// Henry فصل ۱۸: «به FH باید شک کرد وقتی بزرگسال (≥۲۰ سال) LDL-C ≥ ۱۹۰ mg/dL یا
//   non-HDL-C ≥ ۲۲۰ mg/dL داشته باشد. در کودکان، نوجوانان و جوانانِ زیرِ ۲۰ سال،
//   LDL-C ≥ ۱۶۰ mg/dL یا non-HDL-C ≥ ۱۹۰ mg/dL نشانهٔ FH است.»
//
// ⚠️ سن نامشخص = بزرگسال. اکثریتِ برگه‌ها سن دارند و وقتی ندارند، فرضِ اطفال
//    یعنی چسباندنِ متنِ کودک به یک بزرگسال. عمداً یک‌طرفه است: قاعدهٔ اطفال
//    هرگز بدونِ سنِ صریح فعال نمی‌شود. اثرِ عملی‌اش را M81b قفل کرده است.
const isAdultForFh = (age) => age == null || age >= 20;
const isYouthForFh = (age) => age != null && age < 20;

/** دو سیگنالِ FH: LDL و non-HDL. هرکدام ممکن است روی برگه نباشد. */
const fhLdl = (e) => val(e).LDL;
const fhNonHdl = (e) => e.indices?.non_hdl ?? null;

