//    (`dka_hhs_emergency`) شرطش فقط `glu >= 250` بود و فوریتش ثابت
//    `emergency`. یعنی دیابتیِ کنترل‌نشده‌ای با قندِ ۲۶۰ — شایع‌ترین حالتِ
//    ممکن روی یک برگهٔ قند — «فوراً به اورژانس مراجعه کنید» می‌خواند.
//    همان کلاسِ تروپونین در N3: خطا به سمتِ اورژانسِ کاذب، روی حالتِ شایع.
//
// سه چیزِ جدا هم‌زمان غلط بود:
//   ۱) هیچ گیتی برای کتون/بی‌کربنات نداشت، پس روی برگهٔ واقعیِ DKA کنارِ
//      `dka_pattern` می‌نشست و بیمار دو یافتهٔ اورژانسیِ تقریباً یکسان
//      می‌خواند. هیچ dedup ای بینِ دو یافتهٔ هم‌فوریت وجود ندارد —
//      `blocks_others` فقط فوریتِ *پایین‌تر* را می‌پوشاند (کلاسِ N20).
//   ۲) روی قندِ ≥۶۰۰ هم فعال می‌شد و کنارِ `hhs_pattern` می‌نشست، که خودش
//      از قبل با احتیاط نوشته شده و واگذاری‌اش به DKA را هم انجام می‌دهد.
//   ۳) دربارهٔ کتون سکوت می‌کرد، در حالی که تنها سؤالِ تعیین‌کننده همان است.
//
// ⚠️ چرا اصلاً حذف نشد: بدونِ این قاعده، قندِ ۴۸۰ای که کتون/بی‌کربنات کنارش
//    ثبت نشده — یعنی اکثرِ برگه‌های آزمایشگاهی — فقط `glycemia` را می‌گیرد
//    که فوریتش `routine` است. «نوبتِ عادی» جوابِ قندِ ۴۸۰ نیست. حذفِ قاعده
//    یک اورژانسِ کاذب را با یک سکوت عوض می‌کرد (N19).

const KETONE_RE = /ketone|کتون|hydroxybutyrate|بتاهیدروکسی/i;

/** بالاترین قندِ ثبت‌شده روی برگه (ناشتا/تصادفی/دوساعته)، به‌عنوان رکوردِ graded. */
function topGlucose(e) {
  const cand = ["GLU_F", "GLU_RANDOM", "GLU_2H"]
    .map((k) => e.graded.find((g) => g.test === k))
    .filter((g) => g?.value != null);
  if (!cand.length) return null;
  return cand.reduce((a, b) => (b.value > a.value ? b : a));
}

/**
 * وضعیتِ کتون: "positive" | "negative" | "absent".
 * ⚠️ سه‌حالته، نه دوحالته: «اندازه‌گیری‌نشده» با «منفی» یکی نیست. همان چیزی
 *    که N4 دربارهٔ کراتینین می‌گوید — تستِ نبوده، تستِ طبیعی نیست.
 */
function ketoneState(e) {
  const tested = !!e.qual && Object.keys(e.qual).some((k) => /ketone|کتون/i.test(k));
  if (!tested) return "absent";
  return urinePositive(e, KETONE_RE) ? "positive" : "negative";
}

/** وضعیتِ بی‌کربنات: "low" | "normal" | "absent" — به همان دلیلِ بالا سه‌حالته. */
function hco3State(e) {
  const g = e.graded.find((x) => x.test === "HCO3");
  if (!g || g.value == null) return "absent";
  return g.abnormal && g.dir === "low" ? "low" : "normal";
}

/**
 * آیا `dka_pattern` (در patterns_biochem.js) این برگه را برمی‌دارد؟
 *
 * ⚠️ این *آینهٔ* شرطِ آن قاعده است. اگر آن‌جا عوض شود و اینجا نه، برگه‌ای
 *    بینِ دو قاعده می‌افتد و هیچ‌کدام فعال نمی‌شوند — سکوت روی کتواسیدوز،
 *    که بدترین جهتِ شکستِ این برنامه است. N16 می‌گوید «جایگزین وجود دارد»
 *    یک ادعاست تا وقتی اندازه گرفته نشود؛ `M91d` همین را اندازه می‌گیرد.
 *
 * ⚠️ و دقت کنید که آن قاعده فقط GLU_F و GLU_RANDOM را می‌خواند، نه GLU_2H.
 *    پس قندِ دوساعتهٔ ۳۰۰ با کتونِ مثبت را *برنمی‌دارد*. به همین دلیل شرطِ
 *    واگذاری «آن قاعده واقعاً فعال می‌شود» است، نه «عدد از فلان حد گذشت».
 */
function dkaOwns(e) {
  const t = val(e);
  const gluHigh =
    (t.GLU_F != null && t.GLU_F >= 250) || (t.GLU_RANDOM != null && t.GLU_RANDOM >= 250);
  const hco3Low = hco3State(e) === "low";
  const ketone = ketoneState(e) === "positive";
  return (gluHigh && (hco3Low || ketone)) || (hco3Low && ketone);
}

/** آیا `hhs_pattern` این برگه را برمی‌دارد؟ (قندِ ≥۶۰۰ *و* بدونِ شواهدِ کتواسیدوز) */
function hhsOwns(e) {
  const g = topGlucose(e);
  if (!g || g.value < 600) return false;
  return !(hco3State(e) === "low" || ketoneState(e) === "positive");
}

