/** مقدارِ یک تستِ درجه‌بندی‌شده. */
function g(engineOut, key) {
  return (engineOut?.graded ?? []).find((x) => x.test === key) ?? null;
}
const isHigh = (x) => !!x && x.abnormal && x.dir === 'high';
const isLow = (x) => !!x && x.abnormal && x.dir === 'low';
const isNormal = (x) => !!x && !x.abnormal;

