/**
 * هشدارهای پیش‌تحلیلیِ فعال برای این پنل.
 * @returns {{id:string, attachTo:string[], text:string, sources:string[]}[]}
 */
export function preanalyticalCaveats(engineOut) {
  const out = [];
  for (const r of PREANALYTICAL_RULES) {
    try {
      if (!r.match(engineOut)) continue;
      out.push({ id: r.id, attachTo: r.attachTo, text: r.text, sources: S, ...(r.supersedes ? { supersedes: r.supersedes } : {}) });
    } catch {
      /* یک قاعدهٔ خراب نباید موتور را بخواباند — همان قرارداد runPatterns */
    }
  }
  return out;
}

/**
 * هشدارها را به یافته‌های مربوطه بچسبان.
 * هرچه به هیچ یافته‌ای نچسبید، به‌عنوان هشدارِ عمومی برگردانده می‌شود تا
 * بی‌صدا گم نشود (همان درسِ N2: افتادنِ خاموش، بدترین حالتِ ممکن است).
 *
 * @returns {{text:string, sources:string[]}[]} هشدارهای بی‌صاحب
 */
export function attachPreanalytical(findings, caveats) {
  const orphans = [];
  for (const c of caveats) {
    const targets = findings.filter((f) => c.attachTo.includes(f.rule_id));
    if (!targets.length) {
      orphans.push({ text: c.text, sources: c.sources });
      continue;
    }
    for (const f of targets) {
      f.warnings = Array.isArray(f.warnings) ? f.warnings : [];
      // تکرارِ متن ممنوع — همان مشکلی که تورِ ایمنیِ N7 ساخت. «supersedes»: جملهٔ هم‌موضوعِ خودِ یافته جایش را به این می‌دهد.
      if (c.supersedes) f.warnings = f.warnings.filter((w) => !c.supersedes.test(w));
      if (!f.warnings.includes(c.text)) f.warnings.push(c.text);
      f.sources = [...new Set([...(f.sources ?? []), ...c.sources])];
    }
  }
  return orphans;
}
