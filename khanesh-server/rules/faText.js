//
// 🔴 چرا این ماژول وجود دارد (گزارشِ کاربر، برگهٔ ۲۰۲۶-۱۰-۱۶):
//   الگوریتمِ دوجهتهٔ یونیکد (UBA) در متنِ RTL، عددِ لاتین را به «قطعهٔ لاتین»
//   می‌چسباند. نتیجه روی صفحه: «ویتامین B12 251» به‌شکل
//      ویتامین  ‹ 251 B12 ›
//   دیده می‌شد؛ یعنی عدد سمتِ *راستِ* نامِ لاتین می‌افتد، در حالی که خوانندهٔ
//   فارسی انتظار دارد عدد پس از نام (یعنی سمتِ چپِ آن) بیاید.
//
//   اندازه‌گیریِ واقعیِ مرورگر (headless Chrome، دیسکتیشنِ DOM):
//     — «ویتامین B12» + « 251» بدونِ نشانگر ⇒ عدد راستِ نام (راست‌به‌چپِ غلط)
//     — با یک RLM (U+200F) بینِ نام و عدد     ⇒ عدد چپِ نام (درست)
//   در پویشِ ۶۳ ترکیبِ نام/عدد از قالب‌های واقعیِ همین پروژه: بدونِ نشانگر ۳۵
//   حالت غلط، با نشانگر ۰ حالت غلط.
//
// ⚠️ چرا RLM و نه چیزِ دیگر:
//   • LRI/PDI (U+2066/U+2069) مدرن‌ترند ولی python-bidi و فونت‌های کهنه (سرویس‌های
//     بیرونی، PDFِ چاپی، خروجیِ مدل) همیشه پشتیبانی نمی‌کنند.
//   • RLM یک نویسهٔ سطحِ ۱ است، در هر موتورِ دوجهته‌ای پذیرفته است، و در متنِ
//     فارسی هیچ عرضی ندارد.
//   • محافظ (U+2060) عرض می‌گیرد؛ RLM نمی‌گیرد.
//
// ⚠️ نشانگر *فقط* وقتی گذاشته می‌شود که نام با نویسهٔ لاتین/رقم تمام شود.
//   نامِ کاملاً فارسی («هموگلوبین 15.5») نشانگر نمی‌گیرد تا متنِ امروزِ برگه‌های
//   سالم بایت‌به‌بایت عوض نشود و نویسهٔ نامرئیِ بی‌دلیل تولید نشود.
// ============================================================

/** RLM — نشانگرِ راست‌به‌چپ (RIGHT-TO-LEFT MARK). در متنِ فارسی عرض ندارد. */
export const RLM = "\u200F";

/** نامی که با حرفِ لاتین یا رقم تمام می‌شود، مرزِ دوجهته‌ای لازم دارد. */
const NEEDS_MARK = /[\p{Script=Latin}\d]$/u;

/**
 * نام و عدد را برای نمایشِ درست در متنِ RTL به هم می‌چسباند.
 *
 * `joinFaNumber("ویتامین B12", "251")` ⇒ `"ویتامین B12‏ 251"` (یک RLM نامرئی)
 * `joinFaNumber("هموگلوبین", "15.5")`  ⇒ `"هموگلوبین 15.5"` (بدونِ تغییر)
 *
 * @param {string} name  نامِ فارسی/اختصارِ آزمایش (از faName یا رشتهٔ آماده)
 * @param {string|number} value عدد یا رشتهٔ مقدار (همراهِ واحد، اگر هست)
 * @param {string} sep   جداکننده (پیش‌فرض: یک فاصله)
 */
export function joinFaNumber(name, value, sep = " ") {
  const n = String(name ?? "");
  const v = String(value ?? "");
  if (!n || !v) return `${n}${v}`;
  return NEEDS_MARK.test(n) ? `${n}${RLM}${sep}${v}` : `${n}${sep}${v}`;
}

/**
 * همان مشکلِ `joinFaNumber`، ولی برای جمله‌های آزادِ فارسی.
 *
 * خط‌های `minor_line` دست‌نویس‌اند (مثل «MPV 7 fL (بازهٔ مرجع 7.5–11.5): …» یا
 * «ویتامین B12 251: مرزی») و «نام + شماره» در آن‌ها از قبل داخلِ رشته تنیده شده؛
 * پس نمی‌توان از `joinFaNumber` استفاده کرد و باید مرزِ دوجهته‌ای بعد از هر
 * «واژهٔ تمام‌شده به لاتین/رقم» که عددی پسِ آن می‌آید گذاشته شود.
 *
 * قاعدهٔ R1 (تنها قاعدهٔ به‌کاررفته؛ با اندازه‌گیری انتخاب شد):
 *   واژه‌ای که با لاتین/رقم تمام می‌شود + فاصله + عددِ بلافاصله ⇒ RLM میانشان.
 *   پرانتزِ پایانی («(AIP) 1.23») عمداً در دستهٔ واژه نیست: اندازه‌گیریِ مرورگر
 *   نشان داد آن حالت از پیش درست رندر می‌شود (۲ جفت، ۰ غلط) و نشانگرِ اضافه
 *   فقط نویسهٔ نامرئیِ بی‌دلیل می‌ساخت.
 *
 * شواهدِ انتخاب (پیکرهٔ ۱۷ تکه‌ایِ واقعی از `minorParagraph` + مواردِ دشمن‌ساز،
 * هر تکه در headless Chrome و اندازه‌گیریِ getBoundingClientRect):
 *   خام  : ۸ جفتِ «واژهٔ لاتین/رقم + عدد» ⇒ ۶ جفت غلط (عدد سمتِ راستِ نام)
 *   R1   : همان ۸ جفت ⇒ ۰ غلط
 *   — به تکه‌های بی‌لاتین دست نمی‌زند (۴ تکه، ۰ تغییر)
 *   — خودتوان است: markFaNumbers(markFaNumbers(s)) === markFaNumbers(s)
 *     (چون RLM خودش در دستهٔ واژه نیست، اجرای دوباره جفت پیدا نمی‌کند)
 *
 * @param {string} text متنِ آزادِ فارسی (یک یافته یا یک پاراگراف)
 * @returns {string} همان متن با نشانگرهای لازم (یا بایت‌به‌بایت همان متن)
 */
export function markFaNumbers(text) {
  const s = String(text ?? "");
  if (!s) return s;
  return s.replace(/([A-Za-z0-9][A-Za-z0-9.\-/%°µ]*)([ \u00a0]+)(?=[0-9\u06f0-\u06f9])/gu, `$1${RLM}$2`);
}
