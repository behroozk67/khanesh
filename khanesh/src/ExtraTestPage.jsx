// ============================================================
// صفحهٔ آزمایشی که در فرمِ ورودِ دستی نیست — «/test/<slug>».
//
// چیدمان همان چیدمانِ TestPage است (و هر دو همان صفحهٔ آزمایشِ الگو)، اما سه
// تفاوتِ عمدی دارد که هر سه از یک قاعده می‌آیند: **این صفحه آموزشی است و
// وعدهٔ تفسیر نمی‌دهد.**
//
//   ۱. کادرِ وضعیتِ پوشش، بالای متن و نه پایینِ آن. آزمایشی که موتور فقط از
//      روی عکس می‌خواند و آزمایشی که اصلاً پوشش داده نمی‌شود، دو جملهٔ
//      متفاوت می‌گیرند و هیچ‌کدام مبهم نیست.
//   ۲. دکمهٔ «عددت را وارد کن» فقط وقتی هست که جایی برای وارد کردن باشد.
//      برای آزمایشِ tier=soon هیچ دکمه‌ای نیست؛ لینک دادن به فرمی که این خانه
//      را ندارد، کاربر را به بن‌بست می‌برد.
//   ۳. بندِ «تفسیر نتیجه» از REF نمی‌آید (این آزمایش در REF نیست)، پس متنِ
//      بالا/پایین هم ندارد. جای آن `results` می‌نشیند که برای آزمایشِ کیفی
//      «مثبت/منفی» و برای آزمایشِ کمّی «بالا/پایین» را خودش می‌نویسد.
//
// ⚠️ اینجا هم مثل TestPage هیچ محدودهٔ مرجعی چاپ نمی‌شود. تنها عددهایی که
//    نوشته می‌شوند، آستانه‌های نقل‌شده از یک راهنمای منتشرشده‌اند و هر کدام
//    باید `ids` داشته باشند که در sources.js موجود است.
// ============================================================

const srcLine = (id) => {
  const s = SRC[id];
  return s ? `${s.org} — ${s.fa} (${s.year})` : null;
};

