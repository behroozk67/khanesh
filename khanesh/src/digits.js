// ============================================================
// نرمال‌سازی ارقام — فارسی/عربی → لاتین
//
// چرا لازم است: کاربر با کیبورد فارسی «۱۲٫۵» می‌زند و
// parseFloat("۱۲٫۵") برابر NaN است. کدِ فرم روی NaN فقط `return`
// می‌کرد، یعنی مقدار **بی‌صدا** حذف می‌شد و هرگز به موتور نمی‌رسید:
// نه خطایی، نه هایلایتی. این همان «کم‌خوانیِ خاموش» است که بدترین
// حالتِ شکستِ این پروژه است، این بار در ورودِ دستی.
//
// نکتهٔ دومی که با آزمایش در مرورگر معلوم شد: با <input type="number">
// اصلاً فرصتِ نرمال‌سازی وجود ندارد — مرورگر رقمِ غیرلاتین را در سطح
// DOM دور می‌ریزد و e.target.value رشتهٔ خالی برمی‌گردد. برای همین
// ورودی‌های مقدار به type="text" + inputMode="decimal" تغییر کردند.
//
// معادلِ سمت سرور: toNum() در khanesh-server/rules/adapter.js — که از
// قبل همین کار را برای خروجی OCR می‌کرد. این فایل همان قرارداد را به
// سمت کلاینت می‌آورد.
// ============================================================

const FA_ZERO = 0x06f0; // ۰
const AR_ZERO = 0x0660; // ٠

/**
 * ارقام فارسی/عربی → لاتین، ممیز عربی → نقطه، حذف کاراکترهای نامرئی.
 * روی رشته کار می‌کند و رشته برمی‌گرداند تا بشود در onChange استفاده کرد
 * و کاربر همان چیزی را ببیند که فرستاده می‌شود.
 */
export function normalizeDigits(input) {
  if (input == null) return "";
  let s = String(input);

  // ارقام فارسی (U+06F0–U+06F9) و عربی-هندی (U+0660–U+0669)
  s = s.replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - FA_ZERO));
  s = s.replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - AR_ZERO));

  // ممیزِ عربی (U+066B)، ویرگولِ فارسی و ویرگولِ لاتین → نقطه.
  // 🔴 ویرگولِ لاتین قبلاً جداکنندهٔ هزارگان حذف می‌شد: «5,5» → ۵۵. در این فرم هیچ مقداری هزارگان
  //    لازم ندارد (شمارش‌ها ×10³/µL‌اند؛ «250,000» → 250.000 = ۲۵۰ هم درست درمی‌آید)، پس کاما ممیز است.
  //    هم‌ارزِ سمتِ سرور: commaToDot در adapter.js (آزمون‌های M161).
  s = s.replace(/[٫،,]/g, ".");

  // جداکنندهٔ هزارگانِ عربی (U+066C) حذف می‌شود، نه تبدیل
  s = s.replace(/٬/g, "");

  // کاراکترهای نامرئیِ چیدمان که از کپی/پیست می‌آیند:
  // ZWNJ، ZWJ، LRM/RLM، جاسازها و ایزوله‌های bidi، فاصلهٔ بی‌شکست
  s = s.replace(/[​-‏‪-‮⁦-⁩]/g, "");
  s = s.replace(/ /g, " ");

  return s;
}

/**
 * سیاستِ دو دستگاهِ عددی — یک‌جا، چون قبلاً دو کپیِ یکسان داشت
 * (toFa در ResultView.jsx و faNum در analyzeJob.js).
 *
 *   • شمارشی که داخلِ جملهٔ فارسی می‌نشیند («۳ آزمایش خارج از محدوده») → رقم فارسی.
 *   • مقدارِ آزمایش، بازهٔ مرجع، تیتر و واحد → رقم لاتین، داخلِ .num
 *     (isolate + ltr + tabular-nums). بیمار باید عددِ روی کاغذ را عیناً پیدا کند.
 *
 * این تابع فقط برای دستهٔ اول است. هرگز روی مقدارِ آزمایش صدایش نزنید.
 */
export function toFaDigits(n) {
  return String(n).replace(/[0-9]/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[+d]);
}

/**
 * نسخهٔ عددی: بعد از نرمال‌سازی، فقط رقم و نقطه و علامت را نگه می‌دارد.
 * برای وقتی که کاربر واحد را هم تایپ کرده («12.5 mg/dL»).
 */
export function toNumber(input) {
  const s = normalizeDigits(input).replace(/[^\d.\-+]/g, "");
  if (!s) return NaN;
  const n = Number(s);
  return Number.isFinite(n) ? n : NaN;
}
