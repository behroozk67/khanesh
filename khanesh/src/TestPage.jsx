import { lazy, Suspense } from "react";
import { useParams } from "react-router-dom";
import Guide from "./Guide.jsx";
import { REF } from "./labRefs.js";
import { catOfTest, tierLabel } from "./testCatalog.js";
import { CATEGORY_PAGES } from "./guideContent.js";
import { TEST_PAGES } from "./testContent.js";
import { SRC } from "./sources.js";
import { interferenceBlocks, DRUG_POINTER, INTERFERENCE_SOURCES } from "./content/interference/index.js";

// «WHO — راهنمای… (۲۰۲۴)» برای بندِ آستانه‌های راهنما. اگر شناسه در رجیستری
// نباشد، چیزی چاپ نمی‌شود؛ استنادِ بی‌منبع بدتر از نبودِ استناد است.
const srcLine = (id) => {
  const s = SRC[id];
  return s ? `${s.org} — ${s.fa} (${s.year})` : null;
};

// صفحهٔ آزمایش‌هایی که در فرم نیستند، جدا و با import پویا. هر دو فایلِ محتوا
// چند صد کیلوبایت‌اند و بیمارِ صفحهٔ هموگلوبین نباید متنِ ۲۴۱ آزمایشِ دیگر را
// هم دانلود کند — همان استدلالِ lazy در App.jsx، یک لایه پایین‌تر.
const ExtraTestPage = lazy(() => import("./ExtraTestPage.jsx"));

// صفحهٔ یک آزمایش — «/test/<key>».
//
// دو نوع کلید به اینجا می‌رسد و مسیرشان از همین‌جا جدا می‌شود:
//   کلیدِ REF («hb», «fbs») → همین فایل؛ آزمایشی که فرمِ ورودِ دستی دارد.
//   اسلاگِ فهرست («total-ige», «troponin») → ExtraTestPage.
//
// ⚠️ صفحه داشتن ≠ تفسیر شدن. آزمایشی که موتور نمی‌خواندش هم صفحهٔ آموزشی
//    دارد، اما آن صفحه دکمهٔ «عددت را وارد کن» ندارد و وضعیتِ پوششش را صریح
//    می‌نویسد. اگر این دو یکی شوند، صفحه وعدهٔ تفسیری می‌دهد که وجود ندارد —
//    همان چیزی که کامنتِ بالای Tests.jsx از آن پرهیز می‌کند.
//
// ⚠️ اینجا هیچ عددِ محدودهٔ مرجعی چاپ نمی‌شود. REF[k].range(sex, months) بدون
//    سن و جنسیت معنا ندارد و برای کراتینین، HDL، اسید اوریک و فریتین جوابِ
//    متفاوتی می‌دهد. بازه جایی ساخته می‌شود که این دو مشخص باشند: خودِ فرم.
export default function TestPage() {
  const { key } = useParams();
  const m = REF[key];
  if (!m) {
    return (
      <Suspense fallback={<div className="page-loading" dir="rtl" role="status">در حال بارگذاری…</div>}>
        <ExtraTestPage slug={key} />
      </Suspense>
    );
  }

  const x = TEST_PAGES[key] || {};
  const g = catOfTest(key);
  const cp = g ? CATEGORY_PAGES[g.id] : null;

  const blocks = [
    { h2: "دربارهٔ این آزمایش" },
    {
      h3: "هدف آزمایش",
      p: x.purpose ? [] : [
        "این آزمایش بخشی از بررسیِ روتینِ همین دسته است و معمولاً همراه با آزمایش‌های دیگرِ همان پنل درخواست می‌شود، نه به‌تنهایی.",
      ],
      ul: x.purpose,
    },
    {
      h3: "این آزمایش چه چیزی را می‌سنجد؟",
      p: [m.about, ...(x.measures || [])].filter(Boolean),
      ul: x.measuresUl,
    },
    (x.when || x.table) && {
      h3: "چه زمانی درخواست می‌شود؟",
      p: x.when,
      table: x.table,
    },
  ].filter(Boolean);

  // متنِ «بالا/پایین» از خودِ REF می‌آید — همان جمله‌ای که فرم هم نشان می‌دهد.
  const dir = [
    m.high && { b: "اگر بالاتر از محدوده باشد:", t: m.high },
    m.low && { b: "اگر پایین‌تر از محدوده باشد:", t: m.low },
  ].filter(Boolean);

  // ترتیبِ بخش‌ها: انجامِ آزمایش (و «در خانه» فقط اگر شدنی است) → تداخلاتِ
  // دارویی → خطاهای آزمایش → نتیجهٔ آزمایش.
  // ⚠️ «تهیهٔ آزمایش»، «هزینه» و «نتیجه چقدر دقیق است؟» عمداً حذف شدند
  //    (تصمیمِ کاربر، ۲۰۲۶-۱۰-۱۵): دو بخشِ اختصاصیِ هر آزمایش جای متنِ عمومیِ
  //    «دقت» را گرفته‌اند. داده: content/interference/.
  const itf = interferenceBlocks(key, srcLine);
  const blocks2 = [
    { h2: "انجام آزمایش" },
    ...itf.home,
    {
      h3: "پیش از نمونه‌گیری",
      p: [
        x.fasting ||
          "ناشتاییِ اختصاصی لازم نیست، اما اگر همراه با قند یا چربی خون در یک پنل درخواست شده باشد، شرطِ ناشتاییِ آن‌ها را رعایت کنید.",
        DRUG_POINTER,
      ],
    },
    {
      h3: "هنگام نمونه‌گیری",
      p: [
        x.sample ||
          "نمونه خونِ وریدی است و معمولاً از ورید بازو گرفته می‌شود. یک نوارِ کشی بالای بازو بسته می‌شود، محل با الکل تمیز می‌شود و خون در یک یا چند لولهٔ مخصوص جمع می‌شود. کلِ کار چند دقیقه طول می‌کشد.",
      ],
    },
    {
      h3: "پس از نمونه‌گیری",
      p: [
        "بلافاصله می‌توانید به کارهای عادی برگردید، مگر آنکه پزشک چیزِ دیگری گفته باشد. کبودیِ کوچک یا حساسیتِ محلِ نمونه‌گیری شایع است و خودبه‌خود خوب می‌شود؛ فشارِ چند دقیقه‌ای روی محل، احتمالش را کم می‌کند.",
      ],
    },

    ...itf.sections,

    { h2: "نتیجهٔ آزمایش" },
    {
      h3: "دریافت نتیجه",
      p: [
        "جوابدهیِ بیشترِ آزمایش‌های خون همان روز یا روزِ بعد است و بسیاری از آزمایشگاه‌ها جواب را روی سامانهٔ اینترنتی هم می‌گذارند. اگر نمونه به مرکزِ ارجاع فرستاده شود، بیشتر طول می‌کشد و آزمایشگاه این را هنگام نمونه‌گیری می‌گوید.",
      ],
    },
    {
      h3: "تفسیر نتیجه",
      p: [
        "کنارِ این عدد، آزمایشگاه یک محدودهٔ مرجع چاپ می‌کند. آن محدوده به سن و جنسیت بستگی دارد و بین آزمایشگاه‌ها هم کمی فرق می‌کند، بنابراین عدد را همیشه با محدودهٔ همان برگه بسنجید، نه با برگهٔ آزمایشگاهی دیگر.",
        "در این صفحه عمداً هیچ بازه‌ای نوشته نشده است: بازه‌ای که ندانیم برای چه سن و چه جنسیتی است، بیش از آنکه کمک کند گمراه می‌کند. اگر عددِ خودتان را در فرم وارد کنید، بازهٔ متناسب با شما ساخته و کنارِ همان عدد نشان داده می‌شود.",
      ],
      ul: dir.length ? dir : undefined,
      note: x.caveat,
    },
    // آستانه‌ها و معیارهای راهنماهای منتشرشده. عمداً جدا از بندِ بالاست:
    // آن یکی دربارهٔ محدودهٔ مرجعِ آزمایشگاه است و این یکی دربارهٔ معیارِ
    // تشخیصیِ یک راهنما — دو چیزِ متفاوت که مدام جای هم گرفته می‌شوند.
    x.guideline && {
      h3: "آنچه راهنماهای بالینی می‌گویند",
      p: x.guideline.p,
      note: x.guideline.ids
        ? `منبع: ${x.guideline.ids.map((id) => srcLine(id)).filter(Boolean).join("؛ ")}`
        : undefined,
    },
    {
      h3: "آیا آزمایشِ تکمیلی لازم است؟",
      p: [
        x.followup ||
          "یک عددِ بیرون از محدوده به‌تنهایی تشخیص نیست. پزشک معمولاً یا آزمایش را تکرار می‌کند، یا آزمایش‌های دیگری از همان دسته می‌خواهد تا الگو مشخص شود.",
        "موتورِ این برنامه هم دقیقاً همین کار را می‌کند: هیچ آزمایشی را جدا قضاوت نمی‌کند و دنبالِ الگوی چند عددِ کنارِ هم می‌گردد. هر چه از یک برگه بیشتر وارد کنید، تفسیر دقیق‌تر می‌شود.",
      ],
    },
    {
      h3: "پرسش‌هایی که می‌توانید از پزشک بپرسید",
      ul: x.questions || [
        "نتیجهٔ من در محدودهٔ متناسب با سن و جنسیتم هست؟",
        "آیا این عدد نیاز به تکرار دارد؟ با چه فاصله‌ای؟",
        "دارو یا مکملی که مصرف می‌کنم روی این نتیجه اثر گذاشته است؟",
        "آیا لازم است آزمایشِ دیگری هم انجام دهم تا علتش روشن شود؟",
      ],
    },
  ].filter(Boolean);

  // آزمایش‌های مرتبط = بقیهٔ آزمایش‌های همان دسته
  const more = g && {
    h: `آزمایش‌های مرتبط در «${g.t}»`,
    items: g.items
      .filter((it) => it.k !== key)
      .map((it) => ({
        n: it.n,
        to: it.to,
        hint: tierLabel(it),
      })),
  };

  const content = {
    title: m.label,
    updated: cp?.updated || "۷ مرداد ۱۴۰۵",
    aka: x.aka,
    card: {
      h: "راهنمای سریع آزمایش",
      p: x.quick || [m.about],
    },
    blocks,
    more,
    blocks2,
    cta: {
      t: `شاخص ${m.label} را روی برگه دارید؟ با ورود به سامانه تفسیر آزمایش خون آزمایار اپ، وضعیت آن را بر اساس سن، جنسیت و در ارتباط با سایر فاکتورها تحلیل کنید.`,
      // specs/011: «/» صفحهٔ فرود است؛ ابزار در «/app/manual» است و ?test= همان بخش را باز می‌کند.
      to: `/app/manual?test=${key}`,
      label: "ورود به تفسیر آزمایش خون",
    },
    resources: cp?.resources,
    // منابعِ خودِ آزمایش بر منابعِ دسته مقدم است — آستانه‌ای که در متنِ همین
    // صفحه نقل شده باید منبعش پایینِ همین صفحه باشد، نه منبعِ دستهٔ کلی.
    sources: [...new Set([...(x.sources || cp?.sources || ["HENRY", "MEDLINEPLUS"]), ...INTERFERENCE_SOURCES])],
  };

  return <Guide c={content} />;
}
