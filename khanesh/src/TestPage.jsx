// «WHO — راهنمای… (۲۰۲۴)» برای بندِ آستانه‌های راهنما. اگر شناسه در رجیستری
// نباشد، چیزی چاپ نمی‌شود؛ استنادِ بی‌منبع بدتر از نبودِ استناد است.
const srcLine = (id) => {
  const s = SRC[id];
  return s ? `${s.org} — ${s.fa} (${s.year})` : null;
};

