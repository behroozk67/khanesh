export function statusOf(key, v, sex, months) {
  const m = REF[key];
  const r = m.range(sex, months);
  // بررسی بحرانی:
  // اول critFn: منطق سفارشی مثل بیلی‌روبین نوزاد
  if (m.critFn && m.critFn(v, sex, months)) return "crit";
  // سپس crit: بازه ثابت، خارج از آن = بحرانی
  if (m.crit) {
    if (v < m.crit[0] || v > m.crit[1]) return "crit";
  }
  // تست‌هایی که crit یا critFn ندارند، هرگز بحرانی نمی‌شوند (فقط بالا/پایین)
  if (v < r.low) return "below";
  if (v > r.high) return "above";
  // نیاز به پیگیری: در محدوده طبیعی ولی نزدیک مرز (۱۰٪ لبه‌ها)
  const width = (r.high - r.low) || 1;
  const margin = width * 0.1;
  if (v <= r.low + margin || v >= r.high - margin) return "watch";
  return "ok";
}

/**
 * تغییرِ عدد نسبت به نوبتِ قبل.
 *
 * ⚠️ عمداً فقط **جهتِ تغییر** را می‌گوید، نه «بهتر شد / بدتر شد».
 *    نسخهٔ قبلی فاصله از مرکزِ محدوده را حساب می‌کرد و از رویش
 *    better/worse می‌ساخت — یعنی یک قضاوتِ بالینیِ سمتِ کلاینت، آن هم با
 *    فرضِ اینکه برای هر آزمایشی «نزدیک‌تر به مرکز = بهتر» است (برای HDL
 *    یا TSH لزوماً درست نیست). حالا خودِ دو عدد و دو وضعیتشان نشان داده
 *    می‌شود و قضاوت با پزشک می‌ماند.
 *
 *    ضمناً واژگانِ رنگیِ «جهتِ تغییر» عمداً از واژگانِ «داخل/خارج محدوده»
 *    جداست (design-reference §۱.۲): یک چیپِ خنثی، نه سبز/قرمز.
 */
export function deltaOf(prev, curr) {
  if (prev === undefined || prev === "" || curr === undefined || curr === "") return null;
  const p = toNumber(prev), c = toNumber(curr);
  if (isNaN(p) || isNaN(c)) return null;
  const diff = +(c - p).toFixed(4);
  if (diff === 0) return { dir: "same", from: p, to: c, diff: 0 };
  return { dir: diff > 0 ? "up" : "down", from: p, to: c, diff };
}

