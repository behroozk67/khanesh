/**
 * تفسیر ترکیبی — الگوهای چند-تستیِ سمتِ کلاینت.
 *
 * ⚠️ این منطق مالِ khanesh-server/rules/patterns.js است و اینجا فقط به‌عنوان
 *    «نکتهٔ اولیهٔ پیش از تحلیل» زنده مانده. هرگز کنارِ نتیجهٔ موتور نمایش
 *    داده نمی‌شود و هرگز با آن ادغام نمی‌شود.
 */
export function comboInsights(getVal, sex, months, ctx = {}) {
  const out = [];
  // کودک: بی‌محدودهٔ کودک هیچ الگویی نمی‌گوییم (آستانه‌های MCV/فریتین/FBS بزرگسال‌اند).
  if (isPediatricMonths(months)) return out;
  const num = (k) => {
    const v = toNumber(getVal(k));
    return isNaN(v) ? null : v;
  };
  // «پایین بودن» هموگلوبین سن/جنس‌محور است (مرد ~۱۳.۵، نوزاد بسیار بالاتر).
  // قبلاً hb < 12 هاردکد بود و روی مرد و نوزاد کاذب فعال می‌شد؛ حالا از خودِ REF می‌آید.
  // لایهٔ ۴ (P79): هر «بالا/پایین» اینجا از همان محدوده‌ای می‌آید که ردیفِ کنارش با آن رنگ می‌شود (با بارداری).
  //   پیش‌تر آستانه‌ها هاردکد بودند (FBS ≥ 100 درحالی‌که ردیفِ FBS 105 «در محدوده» بود؛ فریتین < 30 درحالی‌که بازهٔ زن از 15 است؛
  //   Hb بدونِ بارداری) و نکته با ردیفِ خودش مخالفت می‌کرد — همان ناسازگاریِ N20 در پیش‌نمایش.
  const rng = (k) => REF[k].range(sex, months, ctx);
  const belowRange = (k, v) => v !== null && v < rng(k).low;
  const aboveRange = (k, v) => v !== null && v > rng(k).high;
  const fbs = num("fbs"), tg = num("tg"), hdl = num("hdl"), chol = num("chol");
  const hb = num("hb"), ferritin = num("ferritin"), mcv = num("mcv");
  const tsh = num("tsh"), t4 = num("t4"), ft4 = num("ft4");
  const iron = num("iron"), tibc = num("tibc");
  const hbLow = belowRange("hb", hb);
  // ۲۰۲۶-۱۰-۱۴: FT4 رایج‌ترین ردیفِ تیروئید روی برگه‌های ایران است؛ قبلاً فقط T4 تام خوانده می‌شد.
  const t4Low = belowRange("ft4", ft4) || belowRange("t4", t4);
  const t4High = aboveRange("ft4", ft4) || aboveRange("t4", t4);

  // مقاومت به انسولین / سندروم متابولیک
  if (aboveRange("fbs", fbs) && aboveRange("tg", tg)) {
    out.push("افزایش هم‌زمان قند خون ناشتا و تری‌گلیسرید می‌تواند نشانه‌ای از مقاومت به انسولین یا سندرم متابولیک باشد؛ بررسی توسط پزشک توصیه می‌شود.");
  }
  // چربی نامطلوب
  if (belowRange("hdl", hdl) && aboveRange("chol", chol)) {
    out.push("همراهی کلسترول تام بالا با کلسترول مفید (HDL) پایین، الگوی نامطلوبی از چربی خون است که با افزایش خطر بیماری‌های قلبی-عروقی همراه است.");
  }
  // کم‌خونی فقر آهن
  if (hbLow && belowRange("ferritin", ferritin)) {
    out.push("کاهش هموگلوبین در کنار پایین بودن فریتین (ذخیرهٔ آهن)، الگوی شایع کم‌خونی فقر آهن است؛ علت آن باید زیر نظر پزشک بررسی شود.");
  } else if (hbLow && ferritin === null && belowRange("iron", iron) && aboveRange("tibc", tibc)) {
    // بی‌فریتین: آهنِ پایین + TIBCِ بالا الگوی کمبودِ آهن است (التهاب TIBC را پایین می‌آورد، نه بالا).
    out.push("کاهش هموگلوبین همراه با آهن سرم پایین و TIBC بالا با کمبود آهن سازگار است؛ اندازه‌گیری فریتین برای تأیید آن کمک می‌کند.");
  }
  if (hbLow && belowRange("mcv", mcv)) {
    out.push("کاهش هموگلوبین همراه با کوچک بودن گلبول‌های قرمز (MCV پایین)، کم‌خونی میکروسیتیک است که شایع‌ترین علت‌های آن کمبود آهن و تالاسمی مینور است.");
  }
  if (hbLow && aboveRange("mcv", mcv)) {
    out.push("کاهش هموگلوبین همراه با بزرگ بودن گلبول‌های قرمز (MCV بالا)، کم‌خونی ماکروسیتیک است که اغلب به کمبود ویتامین B12 یا فولات مربوط است؛ پیش از بررسی پزشک، خودسرانه مکمل شروع نکنید.");
  }
  // کم‌کاری / پرکاری تیروئید
  if (aboveRange("tsh", tsh) && t4Low) {
    out.push("افزایش TSH همراه با کاهش هورمون تیروکسین (Free T4 یا T4 تام)، الگوی کم‌کاری تیروئید است.");
  }
  if (belowRange("tsh", tsh) && t4High) {
    out.push("کاهش TSH همراه با افزایش هورمون تیروکسین (Free T4 یا T4 تام)، الگوی پرکاری تیروئید است و نیاز به بررسی پزشک دارد.");
  }
  return out;
}
