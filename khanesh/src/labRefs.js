/** تبدیل سن به ماه بر اساس واحد (year/month/day). اگر نامعتبر، null. */
export function ageInMonths(age, ageUnit) {
  const a = toNumber(age);
  if (isNaN(a)) return null;
  if (ageUnit === "day") return a / 30;
  if (ageUnit === "month") return a;
  return a * 12; // سال (پیش‌فرض)
}

