import { GUIDES } from "./testCatalog.js";

// ============================================================
// جستجوی آزمایش — ایندکسِ واحدِ همهٔ جست‌وجوهای سرصفحه
//
// ⚠️ این ماژول برای این ساخته شد که دو نسخهٔ واگرا از یک جستجو پدید نیاید.
//    قبلاً جست‌وجوی میانِ صفحهٔ «راهنمای آزمایش‌ها» این منطق را داشت و بعد از
//    حذفش، خانهٔ جستجوی نوار هنوز به شکلِ باریکِ خودش (فقط «نامِ لاتینِ REF»)
//    می‌گشت؛ نتیجه: عبارتِ فارسیِ ناموجود بی‌صدا هیچ‌جا نمی‌رفت.
//    حالا هر دو — فرمِ نوار و پیشنهادهای زنده — از همین یک تابع می‌خوانند.
// ============================================================

// یکسان‌سازیِ متنِ جستجو: حروفِ عربی → فارسی، ارقامِ فارسی/عربی → لاتین،
// فاصله‌های نیم‌فاصله‌ای، و حروفِ کوچک. تایپ با کیبوردِ عربی یا ارقامِ فارسی
// نباید نتیجهٔ خالی بدهد.
export const normQ = (x) =>
  String(x)
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x06f0))
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[‌\s]+/g, " ")
    .trim()
    .toLowerCase();

// ایندکسِ ثابت: همهٔ آزمایشِ همهٔ دسته‌ها، یکتا بر اساس نام (همان قاعدهٔ
// سطل‌های الفبایی در Tests.jsx — یک آزمایش در چند دسته تکرار می‌شود).
const INDEX = (() => {
  const uniq = new Map();
  GUIDES.forEach((g) =>
    g.items.forEach((it) => {
      if (it && !uniq.has(it.n)) uniq.set(it.n, it);
    })
  );
  return [...uniq.values()].map((it) => ({
    it,
    // نام + توضیح + اسلاگ + کلیدِ REF؛ «Hb (هموگلوبین)» هم با «hb» پیدا می‌شود
    // هم با «هموگلوبین».
    hay: normQ(`${it.n} ${it.d || ""} ${it.slug || ""} ${it.k || ""}`),
    name: normQ(it.n),
  }));
})();

// دستِ کمِ عبارت: با یک حرف نتیجهٔ نادرستِ زیاد می‌دهد (همان قاعدهٔ قدیمی).
const MIN_LEN = 2;

// جستجو روی نام/توضیح/اسلاگ؛ همهٔ واژه‌های عبارت باید بیایند («قند ناشتا»).
// ترتیب: اول نامی که با عبارت شروع می‌شود، بعد شاملِ عبارت، بعد بقیه.
export function searchTests(q, limit = 8) {
  const t = normQ(q);
  if (t.length < MIN_LEN) return [];
  const words = t.split(" ");
  const hits = INDEX.filter((r) => words.every((w) => r.hay.includes(w)));
  hits.sort((a, b) => {
    const rank = (r) => (r.name.startsWith(t) ? 0 : r.name.includes(t) ? 1 : 2);
    return rank(a) - rank(b);
  });
  return hits.slice(0, limit).map((r) => r.it);
}

