// ⚠️ قبلاً آزمایشِ فرمی به «/app?test=<k>» می‌رفت. «/app» اولین گامِ ناتمامِ
//    ثبت‌نام را پیدا می‌کند و با Navigate به «/app/intake/…» می‌رود؛ query
//    گم می‌شد و کاربر به‌جای آزمایش، فرمِ مشخصات (شبیهِ پروفایل) را می‌دید.
//    دکمهٔ «وارد کردن عدد» در صفحهٔ آزمایش همان کار را درست انجام می‌دهد.
export const searchHref = (it) => it.to;
