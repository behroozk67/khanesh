// ============================================================
// «تداخلات دارویی» و «چه مواردی باعث خطای آزمایش می‌شود؟» برای هر آزمایش.
//
// یک کلید برای هر آزمایشِ testCatalog (کلیدِ REF برای آزمایش‌های فرم، اسلاگ
// برای بقیه). coverage.mjs بررسی می‌کند که هیچ آزمایشی بی‌مدخل نماند؛ صفحه‌ای
// که مدخل ندارد، این دو بخش را اصلاً نشان نمی‌دهد، نه متنِ عمومیِ بی‌صاحب.
//
// منابع: FDA_BIOTIN، CLSI_SUB، TESTING_COM، MEDLINEPLUS (sources.js).
// ============================================================

import { CORE } from "./core.js";
import { ENDO } from "./endo.js";
import { IMMUNO } from "./immuno.js";
import { OTHER } from "./other.js";

export const INTERFERENCE = { ...CORE, ...ENDO, ...IMMUNO, ...OTHER };

// منابعی که پایینِ این دو بخش نام برده می‌شوند — همان سه مرجعِ اصلی به‌علاوهٔ
// MedlinePlus، که صفحهٔ هر آزمایشش بندِ «چه چیزی نتیجه را تغییر می‌دهد» دارد.
export const INTERFERENCE_SOURCES = ["FDA_BIOTIN", "CLSI_SUB", "TESTING_COM", "MEDLINEPLUS"];

// [عنوان، توضیح] → {b, t} برای فهرستِ Guide.jsx
const asItems = (rows) => (rows || []).map(([b, t]) => ({ b: `${b}:`, t }));

// جمله‌ای که بندِ «پیش از نمونه‌گیری» در هر دو صفحه به بخشِ داروها ارجاع می‌دهد.
export const DRUG_POINTER =
  "داروها و مکمل‌هایی که روی نتیجهٔ همین آزمایش اثر می‌گذارند، در بخشِ «تداخلات دارویی» همین صفحه آمده‌اند. فهرستِ کاملِ داروها و مکمل‌هایتان را به آزمایشگاه بگویید و هیچ دارویی را بدونِ نظرِ پزشک قطع نکنید.";

// بلوک‌های صفحه برای یک آزمایش: «آیا می‌شود در خانه…» (فقط اگر می‌شود)،
// «تداخلات دارویی» و «چه مواردی باعث خطای آزمایش می‌شود؟».
// srcLine از صفحه می‌آید تا قالبِ استناد با بقیهٔ صفحه یکی باشد.
export function interferenceBlocks(key, srcLine) {
  const x = INTERFERENCE[key];
  if (!x) return { home: [], sections: [] };
  const note = `منابع: ${INTERFERENCE_SOURCES.map(srcLine).filter(Boolean).join("؛ ")}`;
  return {
    home: x.home ? [{ h3: "آیا می‌شود در خانه انجامش داد؟", p: [x.home] }] : [],
    sections: [
      { h2: "تداخلات دارویی" },
      {
        p: ["داروها، مکمل‌ها و درمان‌هایی که نتیجهٔ این آزمایش را تغییر می‌دهند. بعضی اثرِ واقعی بر بدن دارند (عدد درست است اما باید با درنظرگرفتنِ دارو خوانده شود) و بعضی خودِ اندازه‌گیری را مخدوش می‌کنند (نتیجهٔ «کاذب»)."],
        ul: asItems(x.drugs),
        note,
      },
      { h2: "چه مواردی باعث خطای آزمایش می‌شود؟" },
      {
        p: ["عواملی پیش از آزمایش و هنگامِ نمونه‌گیری که می‌توانند نتیجهٔ این آزمایش را نادرست نشان دهند. اگر نتیجه با حالِ شما جور نیست، این موارد را با پزشک یا آزمایشگاه مطرح کنید؛ معمولاً تکرارِ آزمایش مشکل را روشن می‌کند."],
        ul: asItems(x.errors),
        note,
      },
    ],
  };
}
