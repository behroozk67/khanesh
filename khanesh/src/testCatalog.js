// فهرستِ دسته‌های آزمایش — تنها منبعِ این تاکسونومی.
//
// هم صفحهٔ «راهنمای آزمایش‌ها» (Tests.jsx) از این می‌خواند، هم صفحهٔ هر دسته
// (CategoryPage) و هم بخشِ «آزمایش‌های مرتبطِ» صفحهٔ هر آزمایش (TestPage).
// قبلاً همین آرایه داخلِ Tests.jsx بود؛ کپی‌کردنش یعنی چند فهرستِ واگرا از یک
// تاکسونومی — همان چیزی که کامنتِ خودِ فایل دربارهٔ «آرایهٔ دستیِ دوم» هشدار
// می‌دهد.
//
// چهار سطحِ پوشش (برچسبی که کنار هر آزمایش نشان داده می‌شود):
//   form  → در فرمِ ورودِ دستی هست (REF)؛ صفحهٔ آزمایشِ خودش را دارد.
//   photo → موتور می‌شناسدش ولی در فرم نیست؛ از روی عکسِ برگه خوانده می‌شود.
//   panel → خودش یک آزمایش نیست، مجموعه‌ای است؛ به صفحهٔ دستهٔ مربوط می‌رود.
//   soon  → پوشش داده نمی‌شود؛ فقط معرفیِ کوتاه، بدون لینک.
// ============================================================

// ---------- آیتم‌های یک دسته ----------
// f("hb")                 → آزمایشِ فرم؛ برچسب/واحد/توضیح از REF می‌آید
// p("Troponin (…)", "…")  → موتور می‌شناسد، از عکسِ برگه خوانده می‌شود
// c("پنل کبد", "…", "disease") → پنل؛ به صفحهٔ آن دسته لینک می‌شود
// s("Total IgE (…)", "…") → هنوز پوشش داده نمی‌شود
const f = (k) => {
  if (!REF[k]) {
    console.warn(`[Tests] کلید ناشناخته در فهرست راهنماها: ${k}`);
    return null;
  }
  return {
    tier: "form", k, n: REF[k].label, u: REF[k].unit, d: REF[k].about,
    to: testPath(k),
  };
};

// نامِ لاتینِ ابتدای هر آزمایش → شناسهٔ مسیر. «Total IgE (IgE تام)» می‌شود
// «total-ige» و «Complement C3 / C4 (کمپلمان)» می‌شود «complement-c3-c4».
//
// ⚠️ اسلاگ از خودِ نام ساخته می‌شود و نه از یک فیلدِ دستیِ کنارِ آن. دلیلش
//    همان دلیلِ PRIMARY_CAT است: یک آزمایش در چند دسته فهرست می‌شود («Zinc»
//    هم در فلزات سنگین و هم در تغذیه، «Rubella IgG» هم در بارداری و هم در
//    ایمنی). با اسلاگِ دستی، دو ورودیِ یک آزمایش می‌توانستند دو اسلاگِ متفاوت
//    بگیرند و کاربر دو صفحهٔ نیمه‌کاره برای یک چیز می‌دید. با اسلاگِ مشتق،
//    هر دو به یک صفحه می‌رسند.
export const testSlug = (name) =>
  name
    .split(" (")[0]
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const extra = (tier) => (n, d) => ({ tier, n, d, slug: testSlug(n), to: testPath(testSlug(n)) });
const p = extra("photo");
const s = extra("soon");
const c = (n, d, cat) => ({ tier: "panel", n, d, to: catPath(cat) });
const pick = (...items) => items.filter(Boolean);

