export const guideById = (id) => GUIDES.find((g) => g.id === id);

// دستهٔ خانهٔ هر آزمایشِ فرم — صفحهٔ آزمایش از این می‌فهمد زیرِ کدام دسته
// بنشیند، منابعش را از کجا بگیرد و «آزمایش‌های مرتبط» را از کجا بیاورد.
// PRIMARY_CAT مقدم است؛ اگر کلیدی آنجا نبود، اولین دسته‌ای که آزمایش در آن
// آمده حساب می‌شود.
export const catOfTest = (k) => {
  const primary = PRIMARY_CAT[k] && guideById(PRIMARY_CAT[k]);
  if (primary && primary.items.some((i) => i.k === k)) return primary;
  return GUIDES.find((g) => g.items.some((i) => i.k === k));
};

export const formTests = () => [...COVERED];

// ---------- آزمایش‌هایی که در فرم نیستند ----------
// همان دو چیزی که catOfTest برای آزمایشِ فرم می‌دهد: خودِ آیتم و دستهٔ خانه‌اش.
export const extraBySlug = (slug) => {
  const hit = (g) => g && g.items.find((i) => i.slug === slug);
  const primary = PRIMARY_CAT_EXTRA[slug] && guideById(PRIMARY_CAT_EXTRA[slug]);
  if (hit(primary)) return { item: hit(primary), cat: primary };
  const g = GUIDES.find((x) => x.items.some((i) => i.slug === slug));
  return g ? { item: hit(g), cat: g } : null;
};

// دو نگهبانِ توسعه، هر دو از جنسِ همان اشتباهی که COVERAGE_GAP می‌گیرد:
//   ۱. اسلاگی که با کلیدِ REF یکی شود، صفحهٔ آزمایشِ فرم را می‌دزدد — چون
//      TestPage اول REF را نگاه می‌کند و آن آزمایش هرگز به صفحهٔ خودش نمی‌رسد.
//   ۲. دو نامِ متفاوت که به یک اسلاگ برسند، یعنی دو آزمایش یک صفحه می‌گیرند.
if (import.meta.env?.DEV) {
  const seen = new Map();
  GUIDES.forEach((g) =>
    g.items.forEach((i) => {
      if (!i.slug) return;
      if (REF[i.slug]) console.warn(`[Tests] اسلاگ با کلیدِ فرم تصادم دارد: ${i.slug} («${i.n}»)`);
      const prev = seen.get(i.slug);
      if (prev && prev !== i.n) console.warn(`[Tests] یک اسلاگ برای دو آزمایش: ${i.slug} («${prev}» و «${i.n}»)`);
      seen.set(i.slug, i.n);
    })
  );
}
