// Regression learning.
//
// A failure that leaves no test behind is a failure you have agreed to have
// again. Every failure the gate finds is turned into a runnable node:test file
// under regressions/ and a line in REGRESSIONS.md. The gate refuses to close a
// failing evaluation until that artefact exists.
import fs from "node:fs";
import path from "node:path";
import { GATE_DIR, ROOT, nowIso, sha256 } from "./util.mjs";

const REG_DIR = path.join(GATE_DIR, "regressions");
const LEDGER = path.join(GATE_DIR, "REGRESSIONS.md");

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);

const HEADER = (id, why, commit) => `// Regression test — generated by eval-gate on ${nowIso()}
// id:      ${id}
// commit:  ${commit}
// why:     ${why}
//
// This file is RED on purpose while the defect is open. Do not delete it to get
// a green run — fix the defect, watch this go green, and leave it in place.
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(fileURLToPath(import.meta.url), "../../../../");
`;

function testForUnresolvedModule(f, id, commit) {
  return HEADER(id, `import "${f.spec}" in ${f.file} does not resolve`, commit) + `
test(${JSON.stringify(`${id} — «${f.spec}» باید واقعاً روی دیسک وجود داشته باشد`)}, () => {
  const importer = path.join(ROOT, ${JSON.stringify(f.file)});
  const spec = ${JSON.stringify(f.spec)};
  const base = path.resolve(path.dirname(importer), spec);
  const candidates = [base, base + ".js", base + ".mjs", base + ".jsx", path.join(base, "index.js")];
  const found = candidates.find((c) => fs.existsSync(c));
  assert.ok(found, \`\${spec} imported from ${f.file}:${f.line} resolves to nothing — \` +
    "a dynamic import fails only at runtime, on the fallback path nobody exercises");
});
`;
}

function testForMissingDependency(f, id, commit) {
  return HEADER(id, `"${f.spec}" imported but not declared in package.json`, commit) + `
test(${JSON.stringify(`${id} — «${f.spec}» باید در package.json اعلام شده باشد`)}, () => {
  const pkgPath = path.join(ROOT, ${JSON.stringify(f.file.split("/")[0])}, "package.json");
  const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));
  const deps = { ...pkg.dependencies, ...pkg.devDependencies, ...pkg.peerDependencies };
  const root = ${JSON.stringify(f.spec.startsWith("@") ? f.spec.split("/").slice(0, 2).join("/") : f.spec.split("/")[0])};
  assert.ok(root in deps, \`\${root} is imported by ${f.file} but missing from \${pkgPath}\`);
});
`;
}

function testForPanel(f, id, commit) {
  return HEADER(id, `golden panel "${f.panel}" failed assertion "${f.assertion}": ${f.msg}`, commit) + `
import { runIntegration } from "../lib/integration.mjs";

test(${JSON.stringify(`${id} — پنل «${f.panel}» نباید دوباره در «${f.assertion}» شکست بخورد`)}, async () => {
  const res = await runIntegration();
  const hit = res.failed.find((x) => x.panel === ${JSON.stringify(f.panel)} && x.assertion === ${JSON.stringify(f.assertion)});
  assert.equal(hit, undefined, hit ? hit.msg : "");
});
`;
}

function testForBoundary(f, id, commit) {
  return HEADER(id, `engine-boundary violation "${f.id}" in ${f.file}:${f.line}`, commit) + `
test(${JSON.stringify(`${id} — قضاوت بالینی نباید دوباره وارد ${f.file} شود`)}, () => {
  const src = fs.readFileSync(path.join(ROOT, ${JSON.stringify(f.file)}), "utf8");
  assert.ok(!src.includes(${JSON.stringify(f.text.slice(0, 120))}),
    ${JSON.stringify(f.msg)});
});
`;
}

function testForDeadCode(f, id, commit) {
  return HEADER(id, `export "${f.symbol}" added by a diff and referenced nowhere`, commit) + `
test(${JSON.stringify(`${id} — «${f.symbol}» یا باید استفاده شود یا حذف`)}, () => {
  const src = fs.readFileSync(path.join(ROOT, ${JSON.stringify(f.file)}), "utf8");
  const declared = new RegExp("export\\\\s+(?:async\\\\s+)?(?:function\\\\*?|const|let|class)\\\\s+" + ${JSON.stringify(f.symbol)}).test(src);
  if (!declared) return; // symbol was removed — the defect is gone
  assert.fail(${JSON.stringify(f.msg)});
});
`;
}

// A reviewer's FAIL has no failing command to re-run, so nothing mechanical can
// be derived from it. What CAN be derived is the reviewer's own citation: the
// file, the line and the exact text it objected to. That is enough for a red
// test that goes green only when the cited text is gone — and enough that the
// finding cannot be closed by forgetting about it.
function testForReviewerFinding(role, ev, id, commit) {
  const quote = typeof ev.quote === "string" ? ev.quote.trim().slice(0, 160) : "";
  const claim = String(ev.claim || "").slice(0, 300);
  const file = ev.file || null;

  // Anchor on the quote only if the cited file is really in the repo right now.
  // A citation pointing outside ROOT (a session transcript, a log) would make the
  // generated test pass by never finding anything to check — the one outcome a
  // regression test must never have. Ten tests generated from the first real run
  // were green for exactly this reason.
  const anchorable = file && quote && !path.isAbsolute(file) && !file.startsWith("..")
    && fs.existsSync(path.join(ROOT, file));

  if (anchorable) {
    return HEADER(id, `${role} reviewer: ${claim}`, commit) + `
test(${JSON.stringify(`${id} — یافتهٔ داور ${role} نباید دوباره برگردد`)}, () => {
  const p = path.join(ROOT, ${JSON.stringify(file)});
  assert.ok(fs.existsSync(p),
    ${JSON.stringify(`${file} no longer exists — if the finding was fixed by deleting it, delete this test deliberately rather than letting it pass silently.`)});
  const src = fs.readFileSync(p, "utf8");
  assert.ok(!src.includes(${JSON.stringify(quote)}),
    ${JSON.stringify(`${claim} (${file}${ev.line ? ":" + ev.line : ""})`)});
});
`;
  }

  // No quotable anchor: still emit a red test, so closing the finding is a
  // deliberate act by someone who read it, not an omission.
  return HEADER(id, `${role} reviewer: ${claim}`, commit) + `
test(${JSON.stringify(`${id} — یافتهٔ داور ${role} هنوز باز است`)}, () => {
  assert.fail(
    ${JSON.stringify(`${claim}\n\nReported by the ${role} reviewer at ${file || "(no file cited)"}${ev.line ? ":" + ev.line : ""}. ` +
      "Replace this with a real assertion of the corrected behaviour, then delete nothing — the file is the record that it was fixed.")}
  );
});
`;
}

/** Turn the evidence bundle's failures into regression artefacts. */
export function generateRegressions(evidence, { commit, dryRun = false } = {}) {
  const created = [];
  const covered = [];
  const checks = evidence.static?.checks || [];

  const emit = (kind, key, body, why) => {
    const id = `${kind}-${slug(key)}-${sha256(key).slice(0, 6)}`;
    const file = path.join(REG_DIR, `${id}.test.mjs`);
    if (fs.existsSync(file)) { covered.push({ id, file: path.relative(GATE_DIR, file), why, note: "already recorded — this defect has been seen before" }); return; }
    if (!dryRun) {
      fs.mkdirSync(REG_DIR, { recursive: true });
      fs.writeFileSync(file, body, "utf8");
    }
    created.push({ id, file: path.relative(GATE_DIR, file).replace(/\\/g, "/"), why, body });
  };

  for (const c of checks) {
    if (c.status !== "fail") continue;
    for (const f of c.findings || []) {
      const id = `${c.id}`;
      if (c.id === "dependency_validation" && f.kind === "unresolved_module") {
        emit("dep", `${f.file}:${f.spec}`, testForUnresolvedModule(f, `dep-${slug(f.spec)}`, commit), f.msg);
      } else if (c.id === "dependency_validation" && f.kind === "missing_dependency") {
        emit("dep", `${f.file}:${f.spec}`, testForMissingDependency(f, `dep-${slug(f.spec)}`, commit), f.msg);
      } else if (c.id === "integration_tests") {
        emit("panel", `${f.panel}:${f.assertion}`, testForPanel(f, `panel-${slug(f.panel)}`, commit), f.msg);
      } else if (c.id === "dead_code") {
        emit("dead", `${f.file}:${f.symbol}`, testForDeadCode(f, `dead-${slug(f.symbol)}`, commit), f.msg);
      } else {
        // lint / typecheck / build failures are already re-detected by the very
        // check that found them — the check is the regression test.
        covered.push({ id: `${id}`, file: `lib/checks.mjs#${id}`, why: `re-detected deterministically by the ${id} check on every run`, note: "no new artefact needed" });
      }
    }
    if (!(c.findings || []).length) {
      covered.push({ id: c.id, file: `lib/checks.mjs#${c.id}`, why: `${c.id} failed without itemised findings — see evidence`, note: "no new artefact needed" });
    }
  }

  for (const v of evidence.medical?.boundary_violations || []) {
    emit("boundary", `${v.file}:${v.id}:${v.text.slice(0, 40)}`, testForBoundary(v, `boundary-${slug(v.id)}`, commit), v.msg);
  }

  // A reviewer's FAIL is a failure like any other. Without this, an LLM-only
  // rejection could block the gate forever without ever producing the artefact
  // the gate demands — found by the gate's own judge on its first real run.
  for (const [role, v] of Object.entries(evidence.verdicts?.present || {})) {
    if (v?.verdict !== "FAIL") continue;
    const items = (v.evidence || []).length ? v.evidence : [{ claim: (v.reasons || [])[0] || `${role} reviewer rejected this change` }];
    for (const ev of items) {
      const key = `${role}:${ev.file || "-"}:${ev.line || 0}:${String(ev.claim).slice(0, 60)}`;
      emit(role, key, testForReviewerFinding(role, ev, slug(String(ev.claim).slice(0, 40)), commit), String(ev.claim).slice(0, 200));
    }
  }

  if (created.length && !dryRun) appendLedger(created, commit);

  return {
    generated: created.length > 0 || covered.length > 0,
    count: created.length,
    created,
    covered_by_existing_check: covered,
    dir: path.relative(GATE_DIR, REG_DIR),
  };
}

function appendLedger(created, commit) {
  const head = fs.existsSync(LEDGER) ? "" : `# Regression Ledger

Every line is a defect the evaluation gate caught once. The test file next to it
is what stops it coming back. Nothing is removed from this list when it is fixed —
a closed entry is the proof that the check still runs.

| date | commit | id | defect | test |
|---|---|---|---|---|
`;
  const rows = created.map((c) => `| ${nowIso().slice(0, 10)} | \`${(commit || "").slice(0, 7)}\` | ${c.id} | ${String(c.why).replace(/\|/g, "\\|").slice(0, 160)} | [${c.file}](${c.file}) |`).join("\n");
  fs.appendFileSync(LEDGER, head + rows + "\n", "utf8");
}
