// Copies the Azmayar site's encyclopedia data modules verbatim into src/content/khanesh/.
// The sibling repo is read-only reference; this script is the only file that names its path.
// Run: node scripts/sync-content.mjs            (write)
//      node scripts/sync-content.mjs --check    (verify only; exits 1 on any drift, writes nothing)
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const checkOnly = process.argv.includes("--check");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Two layouts are supported: the app as its own checkout (the site repo is the sibling
// `khanesh-project/`) and the app as the `mobile/` folder of that repo (the site is the parent).
// Never hard-code one of them.
const firstExisting = (...candidates) => candidates.find((p) => existsSync(p));
const SITE_SRC = firstExisting(
  join(root, "..", "khanesh", "src", "labRefs.js"),
  join(root, "..", "khanesh-project", "khanesh", "src", "labRefs.js"),
);
const SCORE_JS = firstExisting(
  join(root, "..", "khanesh-server", "rules", "score.js"),
  join(root, "..", "khanesh-project", "khanesh-server", "rules", "score.js"),
);
const SRC = SITE_SRC ? dirname(SITE_SRC) : join(root, "..", "khanesh-project", "khanesh", "src");
const OUT = join(root, "src", "content", "khanesh");

const FILES = ["labRefs.js", "digits.js", "testCatalog.js", "testContent.js", "testSearch.js", "guideContent.js", "sources.js", "testCategories.js", "resultModel.js"];

// EAS cloud builds have no sibling repo: keep the committed copy.
if (!existsSync(SRC)) { console.log("sync-content: site source not found, keeping committed copy"); process.exit(0); }

const HEADER = "// GENERATED by scripts/sync-content.mjs from khanesh/src — do not edit.\n";
// Everything is built in memory first: `--check` must never write, and the drift guard must run before rmSync.
const outputs = new Map();
for (const f of FILES) {
  // The one transform: Vite's import.meta.env is a dev-only guard Hermes can't parse.
  const text = readFileSync(join(SRC, f), "utf8").replaceAll("import.meta.env?.DEV", "false");
  outputs.set(f, HEADER + text);
}
const skipContent = (name) => /\.(test\.js|mjs)$/.test(name);
const collect = (dir, base = dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) { collect(full, base); continue; }
    if (skipContent(entry.name)) continue;
    outputs.set(join("content", relative(base, full)), readFileSync(full));
  }
};
collect(join(SRC, "content"));

// Info pages are JSX prose on the site. Extract their h1/h2/h3/p/li text in order (tags stripped, words kept verbatim).
const PAGES = {
  "reference-ranges": "ReferenceRanges.jsx",
  "units-guide": "UnitsGuide.jsx",
  "how-to-capture": "HowToCapture.jsx",
  methodology: "Methodology.jsx",
  terms: "TermsPage.jsx",
  privacy: "PrivacyPage.jsx",
};
const clean = (s) =>
  s
    .replace(/\{"\s*"\}/g, " ")
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim();
const pages = {};
for (const [id, file] of Object.entries(PAGES)) {
  const jsx = readFileSync(join(SRC, file), "utf8");
  const body = jsx.slice(jsx.indexOf("return ("));
  const blocks = [];
  for (const m of body.matchAll(/<(h1|h2|h3|p|li)\b[^>]*>([\s\S]*?)<\/\1>/g)) {
    const tag = m[1];
    const text = clean(m[2]);
    if (!text) continue;
    const before = body.slice(0, m.index);
    const ordered = tag === "li" && before.lastIndexOf("<ol") > before.lastIndexOf("</ol>");
    blocks.push(ordered ? { t: "li", text, ordered: true } : { t: tag, text });
  }
  if (blocks.some((b) => /[{}]/.test(b.text))) throw new Error(`${file}: unhandled JSX expression in text`);
  pages[id] = blocks;
}
// App-side legal edits: the site is read-only here, so these are applied on top of its text on every sync.
const ADDED_TERMS = [
  ["h2", "۶. پرداخت، بازپرداخت و لغو پلن"],
  ["p", "خدمات پولی به‌صورت نوبت تفسیر (اعتبار) عرضه می‌شود. مبلغ هر پلن پیش از پرداخت در صفحهٔ درگاه نمایش داده می‌شود و پرداخت از طریق درگاه بانکی (زرین‌پال) انجام می‌شود؛ اطلاعات کارت بانکی نزد آزمایار اپ نگهداری نمی‌شود. اعتبار فقط پس از تأیید پرداخت توسط سرور فعال می‌شود."],
  ["p", "پلن‌ها اشتراک تمدیدشونده نیستند و تمدید خودکار ندارند؛ بنابراین لغو اشتراک لازم نیست و با مصرف یا نخریدن دوباره، هزینه‌ای کسر نمی‌شود."],
  ["p", "اگر مبلغ کسر شده ولی اعتبار فعال نشده یا به‌دلیل خطای سامانه تفسیری ارائه نشده است، با ذکر کد پیگیری از صفحهٔ تماس با آزمایار اپ درخواست بررسی بدهید؛ پس از تأیید، مبلغ به همان کارت بازگردانده یا اعتبار جبران می‌شود. نوبت‌های مصرف‌شده و تفسیرهای ارائه‌شده قابل بازپرداخت نیستند."],
  ["h2", "۷. محدودیت مسئولیت"],
  ["p", "سامانه «به همان صورتی که هست» ارائه می‌شود. خواندن خودکار برگه ممکن است خطا داشته باشد یا برگهٔ ناخوانا کامل خوانده نشود؛ کاربر باید مقادیر استخراج‌شده را با برگهٔ اصلی تطبیق دهد. آزمایار اپ در برابر تصمیم یا اقدام درمانی که کاربر بر پایهٔ خروجی سامانه انجام دهد مسئولیتی ندارد و در حد مجاز قانون، مسئول زیان غیرمستقیم نیست."],
  ["h2", "۸. قانون حاکم و حل اختلاف"],
  ["p", "این شرایط تابع قوانین جمهوری اسلامی ایران است. اختلاف ابتدا از راه گفت‌وگو و در غیر این صورت در مراجع صالح قضایی ایران رسیدگی می‌شود."],
].map(([t, text]) => ({ t, text }));
for (const b of pages.terms) {
  if (b.text.startsWith("استفاده از این سامانه برای کاربران ۱۸ سال به بالا مجاز است."))
    b.text = "استفاده از این سامانه برای کاربران ۱۸ سال به بالا مجاز است و هنگام ورود باید ۱۸ سال تمام داشتن خود را تأیید کنید." + b.text.slice("استفاده از این سامانه برای کاربران ۱۸ سال به بالا مجاز است.".length);
}
pages.terms.push(...ADDED_TERMS);
for (const b of pages.privacy) b.text = b.text.replace(" (`khanesh-server/rules/`)", "");
// The hero menu's clinical-sources link is a section of the site's landing page: same words, as its own page.
const landing = readFileSync(join(SRC, "Landing.jsx"), "utf8");
const after = (mark, end) => {
  const from = landing.indexOf(mark);
  return landing.slice(from, landing.indexOf(end, from));
};
const sources = [...after("const sources = [", "];").matchAll(/n: "(.*?)", r: "(.*?)"/g)];
const lede = after('id="basis"', "</p>").match(/site-lede">([\s\S]*)/);
if (!sources.length || !lede) throw new Error("Landing.jsx: sources section not found");
pages.basis = [
  { t: "h1", text: "مبنای علمی" },
  { t: "p", text: clean(lede[1]).replace("{BRAND}", "آزمایار اپ") },
  ...sources.map((m) => ({ t: "li", text: `${m[1]}: ${m[2]}` })),
];
outputs.set("pages.js", `${HEADER}export const PAGES = ${JSON.stringify(pages, null, 2)};\n`);

// Drift guard: the server's score threshold must equal the site's radar threshold the app copies.
// Skipped when the server checkout is absent (EAS cloud build, or a lone `mobile/` folder).
// Fail closed: a renamed/removed constant must not turn the guard into a no-op.
if (SCORE_JS) {
  const serverMin = readFileSync(SCORE_JS, "utf8").match(/MIN_SYSTEMS\s*=\s*(\d+)/)?.[1];
  const siteMin = String(outputs.get("resultModel.js")).match(/RADAR_MIN_SYSTEMS\s*=\s*(\d+)/)?.[1];
  if (!serverMin || !siteMin) throw new Error(`score threshold guard: constant not found (server=${serverMin}, site=${siteMin})`);
  if (serverMin !== siteMin) throw new Error(`score threshold drift: server MIN_SYSTEMS=${serverMin}, site RADAR_MIN_SYSTEMS=${siteMin}`);
}

if (checkOnly) {
  const drift = [];
  // EOL-insensitive: `git archive` (what the pre-commit hook checks) applies CRLF on a Windows
  // checkout with core.autocrlf=true, while this script always writes LF. Blobs are LF either way,
  // so the gate must compare content, not line endings — otherwise every mobile commit is red here.
  const norm = (buf) => buf.toString("utf8").replace(/\r\n/g, "\n");
  for (const [rel, want] of outputs) {
    const file = join(OUT, rel);
    if (!existsSync(file)) { drift.push(`missing: ${rel}`); continue; }
    const wantBuf = typeof want === "string" ? Buffer.from(want, "utf8") : want;
    if (norm(readFileSync(file)) !== norm(wantBuf)) drift.push(`differs: ${rel}`);
  }
  const known = new Set(outputs.keys());
  const walkOut = (dir, base = dir) => {
    if (!existsSync(dir)) return;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) { walkOut(full, base); continue; }
      const rel = relative(base, full);
      if (!known.has(rel)) drift.push(`extra: ${rel}`);
    }
  };
  walkOut(OUT);
  if (drift.length) {
    console.error(`sync-content --check: ${drift.length} file(s) out of sync\n  ${drift.join("\n  ")}`);
    process.exit(1);
  }
  console.log("sync-content --check: in sync");
  process.exit(0);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const [rel, content] of outputs) {
  const file = join(OUT, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}
const copied = [...outputs.keys()].filter((k) => k.startsWith("content")).length;
console.log(`synced ${FILES.length} modules + ${copied} content files + ${Object.keys(pages).length} pages → src/content/khanesh`);
